#!/usr/bin/env python3
"""Writes `security/random/src/kat.rs`: the constants of the generator's known-answer self-test.

The self-test (NIST SP 800-90A Rev. 1 section 11.3) runs in the kernel and the loader before a
generator is first instantiated, so its vectors are compiled in. They are NIST's own: the first
vector with prediction resistance and the first with a reseed from the ACVP set for HMAC_DRBG
over SHA-512 that `security/crypto/tests/vectors/acvp/hmac-drbg-sha2-512.txt` holds (owner
decision 145; NIST's notice is beside that file).

    python3 -I security/random/tools/gen_selftest.py            # writes the file
    python3 -I security/random/tools/gen_selftest.py --check    # fails if the file differs

A host test in `selftest.rs` reads the vector file again and compares it with the compiled
constants, so the two cannot drift apart unseen. Development tool only; nothing here ships.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
VECTORS = ROOT / "security/crypto/tests/vectors/acvp/hmac-drbg-sha2-512.txt"
OUT = ROOT / "security/random/src/kat.rs"


def unhex(text):
    return b"" if text == "-" else bytes.fromhex(text)


def vectors():
    found = []
    for line in VECTORS.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        cols = line.split(" ")
        if cols[0] == "drbg":
            _, tc, kind, entropy, nonce, personalization, answer = cols
            found.append(
                {
                    "tc": int(tc),
                    "kind": kind,
                    "entropy": unhex(entropy),
                    "nonce": unhex(nonce),
                    "personalization": unhex(personalization),
                    "answer": unhex(answer),
                    "steps": [],
                }
            )
        elif cols[0] == "in":
            _, step, entropy, additional = cols
            entropy, additional = unhex(entropy), unhex(additional)
            if step == "reseed":
                name = "Reseed"
            elif entropy:
                name = "Fresh"
            else:
                name = "Generate"
            found[-1]["steps"].append((name, entropy, additional))
        else:
            raise SystemExit(f"malformed line: {line[:60]}")
    return found


def array(name, data):
    lines = [f"#[rustfmt::skip]\nconst {name}: [u8; {len(data)}] = ["]
    for at in range(0, len(data), 16):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in data[at : at + 16]))
    lines.append("];")
    return "\n".join(lines)


def render():
    every = vectors()
    chosen = [
        next(v for v in every if v["kind"] == "pr"),
        next(v for v in every if v["kind"] == "reseed"),
    ]
    out = [
        "//! The known-answer self-test's vectors: NIST's, from the ACVP set for HMAC_DRBG over SHA-512",
        "//! (owner decision 145). Generated by `security/random/tools/gen_selftest.py` from",
        "//! `security/crypto/tests/vectors/acvp/hmac-drbg-sha2-512.txt`; do not edit by hand. A host",
        "//! test in `selftest.rs` compares these constants with that file.",
        "",
        "use crate::selftest::{Step, Vector};",
        "",
    ]
    names = []
    for v in chosen:
        prefix = f"TC{v['tc']}"
        for field in ("entropy", "nonce", "personalization", "answer"):
            out.append(array(f"{prefix}_{field.upper()}", v[field]))
        steps = []
        for number, (name, entropy, additional) in enumerate(v["steps"]):
            if name == "Generate":
                out.append(array(f"{prefix}_STEP{number}_ADDITIONAL", additional))
                steps.append(
                    f"        Step::Generate {{\n            additional: &{prefix}_STEP{number}_ADDITIONAL,\n        }},"
                )
            else:
                out.append(array(f"{prefix}_STEP{number}_ENTROPY", entropy))
                out.append(array(f"{prefix}_STEP{number}_ADDITIONAL", additional))
                steps.append(
                    f"        Step::{name} {{\n            entropy: &{prefix}_STEP{number}_ENTROPY,\n"
                    f"            additional: &{prefix}_STEP{number}_ADDITIONAL,\n        }},"
                )
        what = (
            "two requests with prediction resistance"
            if v["kind"] == "pr"
            else "a reseed, then two requests"
        )
        out.append("")
        out.append(f"/// NIST's vector tcId {v['tc']}: {what}.")
        out.append(f"const {prefix}: Vector = Vector {{")
        out.append(f"    tc: {v['tc']},")
        out.append(f"    entropy: &{prefix}_ENTROPY,")
        out.append(f"    nonce: &{prefix}_NONCE,")
        out.append(f"    personalization: &{prefix}_PERSONALIZATION,")
        out.append("    steps: &[")
        out.extend(steps)
        out.append("    ],")
        out.append(f"    answer: &{prefix}_ANSWER,")
        out.append("};")
        out.append("")
        names.append(prefix)
    out.append("/// The vectors the self-test runs.")
    out.append(f"pub(crate) const VECTORS: [Vector; {len(names)}] = [{', '.join(names)}];")
    return "\n".join(out) + "\n"


def main():
    text = render()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != text:
            raise SystemExit(f"{OUT} differs from what this tool writes")
        print(f"{OUT.relative_to(ROOT)} is what this tool writes")
        return
    if sys.argv[1:]:
        raise SystemExit(__doc__)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
