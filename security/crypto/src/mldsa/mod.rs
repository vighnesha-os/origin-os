//! ML-DSA signature verification (FIPS 204, August 2024): ML-DSA.Verify (Algorithm 3) and
//! ML-DSA.Verify_internal (Algorithm 8) for ML-DSA-65 and ML-DSA-87, the post-quantum half
//! of the ONBF signature suites OSS-1 and OSS-1R (ONBF §7.1–§7.2). Pure ML-DSA only:
//! HashML-DSA (pre-hash, Algorithm 5) is not provided.
//!
//! The message representative is M′ = 0 ‖ |ctx| ‖ ctx ‖ M (Algorithm 3 step 2). ONBF passes
//! the exact statement bytes as M and `origin/onbf/1/<role>` as ctx.
//!
//! Strict semantics, checked in this order; the first failure is the result:
//! 1. The context string is at most 255 bytes (Algorithm 3 step 1): `ContextTooLong`.
//! 2. The hint decodes (sigDecode's HintBitUnpack, Algorithm 21; Algorithm 8 step 3
//!    rejects ⊥), checked in Algorithm 21's own order, polynomial by polynomial:
//!    - the cumulative count of polynomial i is below that of polynomial i − 1, or above ω:
//!      `HintCountOutOfRange`;
//!    - the positions within polynomial i are not strictly increasing:
//!      `HintIndexNotIncreasing`;
//!
//!    and after the last polynomial, a position byte beyond the last used one is non-zero:
//!    `HintPaddingNonZero`.
//! 3. ‖z‖∞ < γ1 − β (Algorithm 8 step 13, first conjunct): `ZOutOfRange`.
//! 4. c̃ = c̃′ = H(μ ‖ w1Encode(UseHint(h, Az − ct1·2^d)), λ/4) (steps 4–13):
//!    `ChallengeMismatch`.
//!
//! Step 13 is a conjunction, so checking the z bound before computing c̃′ (it is cheap,
//! and it fails early) does not change any verdict. pkDecode and z's BitUnpack cannot fail:
//! every byte string of the right length is a valid public key, and every 20-bit field is a
//! z coefficient in [−γ1 + 1, γ1].
//!
//! Stack: Â (ℓ·k polynomials, 56 KiB for ML-DSA-87) is never materialized. Each entry
//! Â[i][j] is regenerated by RejNTTPoly when row i is computed and multiplied into the row
//! coefficient by coefficient as it is sampled; each row of w′1 is then encoded and
//! absorbed into the SHAKE256 state computing c̃′, so neither w′ nor w′1 is stored either.
//! What is held is NTT(z) (ℓ KiB), NTT(c), the row and its NTT(t1·2^d) (1 KiB each), the
//! hints as k 256-bit masks and three SHAKE states. The release build's peak is about
//! 15 KiB for ML-DSA-87 and 13 KiB for ML-DSA-65, against a 24 KiB budget
//! (`verify_peak_stack_measured` in `src/tests_mldsa.rs`).
//!
//! Variable time: verification handles public data only (ONBF §7.2), so loop counts and
//! early returns depend on the key, message and signature freely, as in Ed25519.

