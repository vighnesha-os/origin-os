/// ML-DSA-65 public-key length in bytes (FIPS 204 Table 2).
pub const MLDSA65_PUBLIC_KEY_BYTES: usize = 1952;
/// ML-DSA-65 signature length in bytes (FIPS 204 Table 2).
pub const MLDSA65_SIGNATURE_BYTES: usize = 3309;
/// ML-DSA-87 public-key length in bytes (FIPS 204 Table 2).
pub const MLDSA87_PUBLIC_KEY_BYTES: usize = 2592;
/// ML-DSA-87 signature length in bytes (FIPS 204 Table 2).
pub const MLDSA87_SIGNATURE_BYTES: usize = 4627;

/// Why a signature was rejected. Each variant names the first failing check, in the order
/// of the module documentation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MlDsaError {
    /// The context string is longer than 255 bytes (FIPS 204 Algorithm 3 step 1).
    ContextTooLong,
    /// A hint count byte is below the previous polynomial's count or above ω
    /// (Algorithm 21 step 4).
    HintCountOutOfRange,
    /// The hint positions of one polynomial are not strictly increasing (Algorithm 21
    /// step 9).
    HintIndexNotIncreasing,
    /// A hint position byte after the last used one is not zero (Algorithm 21 step 17).
    HintPaddingNonZero,
    /// A coefficient of z has |z| ≥ γ1 − β (Algorithm 8 step 13).
    ZOutOfRange,
    /// Every encoding is valid, but c̃ differs from the recomputed c̃′ (Algorithm 8 step 13):
    /// the signature is not for this key, message and context.
    ChallengeMismatch,
}

/// Verifies an ML-DSA-65 `signature` on `message` with context string `context` under
/// `public_key` (FIPS 204 Algorithm 3), with the strict checks of the module documentation.
pub fn mldsa65_verify(
    public_key: &[u8; MLDSA65_PUBLIC_KEY_BYTES],
    message: &[u8],
    context: &[u8],
    signature: &[u8; MLDSA65_SIGNATURE_BYTES],
) -> Result<(), MlDsaError> {
    verify::<MlDsa65, { MlDsa65::K }, { MlDsa65::L }>(public_key, message, context, signature)
}

/// Verifies an ML-DSA-87 `signature` on `message` with context string `context` under
/// `public_key` (FIPS 204 Algorithm 3), with the strict checks of the module documentation.
pub fn mldsa87_verify(
    public_key: &[u8; MLDSA87_PUBLIC_KEY_BYTES],
    message: &[u8],
    context: &[u8],
    signature: &[u8; MLDSA87_SIGNATURE_BYTES],
) -> Result<(), MlDsaError> {
    verify::<MlDsa87, { MlDsa87::K }, { MlDsa87::L }>(public_key, message, context, signature)
}

// The public lengths are the parameter sets' Table 2 lengths.
const _: () = assert!(
    MLDSA65_PUBLIC_KEY_BYTES == MlDsa65::PUBLIC_KEY_BYTES
        && MLDSA65_SIGNATURE_BYTES == MlDsa65::SIGNATURE_BYTES
        && MLDSA87_PUBLIC_KEY_BYTES == MlDsa87::PUBLIC_KEY_BYTES
        && MLDSA87_SIGNATURE_BYTES == MlDsa87::SIGNATURE_BYTES
);

/// ML-DSA.Verify (Algorithm 3) and Verify_internal (Algorithm 8) for parameter set `P`;
/// `K` and `L` are `P::K` and `P::L` (they size arrays, which an associated constant
/// cannot do on stable Rust).
fn verify<P: ParameterSet, const K: usize, const L: usize>(
    public_key: &[u8],
    message: &[u8],
    context: &[u8],
    signature: &[u8],
) -> Result<(), MlDsaError> {
    // Evaluated per parameter set at compile time: the layouts and the fixed-width
    // encodings below are those of this parameter set.
    const {
        assert!(K == P::K && L == P::L);
        assert!(P::PUBLIC_KEY_BYTES == 32 + encoding::T1_ROW_BYTES * K);
        assert!(P::SIGNATURE_BYTES == P::CTILDE_BYTES + encoding::Z_POLY_BYTES * L + P::OMEGA + K);
        assert!(P::CTILDE_BYTES == P::LAMBDA / 4 && P::CTILDE_BYTES <= 64);
        assert!(P::BETA as usize == P::TAU * P::ETA as usize);
        // z is packed in 20-bit fields only for γ1 = 2^19, and w1 in 4-bit values only for
        // m = (q − 1)/(2γ2) = 16.
        assert!(P::GAMMA1 == 1 << 19);
        assert!((Q - 1) / (2 * P::GAMMA2) == 16 && (Q - 1).is_multiple_of(2 * P::GAMMA2));
    };

    // Algorithm 3 step 1. |ctx| is then the second byte of M′.
    let Ok(context_len) = u8::try_from(context.len()) else {
        return Err(MlDsaError::ContextTooLong);
    };
    // pkDecode and sigDecode (Algorithm 8 steps 1–2). The public functions fix both lengths
    // and the assertions above tie them to K and L, so the split always succeeds; if it
    // ever did not, verification would fail closed.
    let (Some(pk), Some(sig)) = (
        split_public_key::<K>(public_key),
        split_signature::<L>(signature, P::CTILDE_BYTES),
    ) else {
        return Err(MlDsaError::ChallengeMismatch);
    };
    // Step 3: h = ⊥ for a malformed hint.
    let mut hints = [[0u64; N / 64]; K];
    hint_bit_unpack::<P, K>(sig.hint, &mut hints)?;
    // Step 13's first conjunct, ‖z‖∞ < γ1 − β, checked while decoding; then NTT(z).
    let mut z_hat = [[0u32; N]; L];
    for (dst, bytes) in z_hat.iter_mut().zip(sig.z) {
        decode_z::<P>(bytes, dst)?;
        ntt(dst);
    }
    // Steps 6–7: tr = H(pk, 64) and μ = H(tr ‖ M′, 64).
    let mut tr = [0u8; 64];
    let mut h = Shake256::new();
    h.update(public_key);
    h.finalize_xof().squeeze(&mut tr);
    let mut mu = [0u8; 64];
    let mut h = Shake256::new();
    h.update(&tr);
    h.update(&[0, context_len]);
    h.update(context);
    h.update(message);
    h.finalize_xof().squeeze(&mut mu);
    // Step 8: c = SampleInBall(c̃), used as NTT(c).
    let mut c_hat = [0u32; N];
    sample_in_ball::<P>(sig.ctilde, &mut c_hat);
    ntt(&mut c_hat);
    // Steps 9–12, one row at a time: w′_i = NTT⁻¹(Σ_j Â[i][j] ∘ NTT(z_j) − NTT(c) ∘
    // NTT(t1_i·2^d)), then w′1_i = UseHint(h_i, w′_i), encoded and absorbed after μ.
    let mut challenge = Shake256::new();
    challenge.update(&mu);
    let mut row = 0u8;
    for (t1_row, row_hints) in pk.t1.iter().zip(&hints) {
        let mut w = [0u32; N];
        let mut column = 0u8;
        for z in &z_hat {
            add_matrix_entry_product(&mut w, pk.rho, row, column, z);
            column = column.wrapping_add(1);
        }
        let mut t1_hat = [0u32; N];
        t1_times_2d(t1_row, &mut t1_hat);
        ntt(&mut t1_hat);
        for ((wc, &t), &c) in w.iter_mut().zip(&t1_hat).zip(&c_hat) {
            *wc = sub(*wc, mul(c, t));
        }
        inverse_ntt(&mut w);
        let mut packed = [0u8; W1_POLY_BYTES];
        w1_encode_row::<P>(&w, row_hints, &mut packed);
        challenge.update(&packed);
        row = row.wrapping_add(1);
    }
    // Steps 12–13: c̃′ = H(μ ‖ w1Encode(w′1), λ/4), compared with c̃.
    let mut buffer = [0u8; 64];
    let recomputed = buffer.get_mut(..P::CTILDE_BYTES).unwrap_or_default();
    challenge.finalize_xof().squeeze(recomputed);
    let differences = recomputed
        .iter()
        .zip(sig.ctilde)
        .fold(0u8, |acc, (a, b)| acc | (a ^ b));
    if differences == 0 && recomputed.len() == sig.ctilde.len() && !recomputed.is_empty() {
        Ok(())
    } else {
        Err(MlDsaError::ChallengeMismatch)
    }
}
