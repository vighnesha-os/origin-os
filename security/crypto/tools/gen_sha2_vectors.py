#!/usr/bin/env python3
"""Generate SHA-256/SHA-512 differential test vectors for origin-crypto (ONBF §13 item 2).

Each vector hashes a deterministic message: byte i of the n-byte message is
(i * 31 + n * 7 + 13) mod 256. src/tests.rs rebuilds the same messages.

Every digest is computed by two independent reference implementations, Python's
hashlib (OpenSSL) and the system `shasum` (Perl Digest::SHA), and is written only if they
agree. Host-only engineering tool; nothing here ships.

Usage: python3 -I gen_sha2_vectors.py > ../tests/vectors/sha2-differential.txt
"""

import hashlib
import subprocess
import sys

LENGTHS = list(range(0, 301)) + [511, 512, 513, 1000, 4095, 4096, 4097, 65536, 1_000_003]


def message(n: int) -> bytes:
    return bytes((i * 31 + n * 7 + 13) & 0xFF for i in range(n))


def shasum(alg: str, data: bytes) -> str:
    out = subprocess.run(["shasum", "-a", alg], input=data, capture_output=True, check=True)
    return out.stdout.split()[0].decode()


def main() -> None:
    print("# SHA-2 differential vectors for origin-crypto. Generated by")
    print("# security/crypto/tools/gen_sha2_vectors.py; hashlib and shasum agreed on every line.")
    print("# Message n: byte i = (i * 31 + n * 7 + 13) mod 256.")
    print("# Columns: length sha256 sha512")
    for n in LENGTHS:
        m = message(n)
        h256, h512 = hashlib.sha256(m).hexdigest(), hashlib.sha512(m).hexdigest()
        if shasum("256", m) != h256 or shasum("512", m) != h512:
            sys.exit(f"reference implementations disagree at length {n}")
        print(n, h256, h512)


if __name__ == "__main__":
    main()
