def check_rfc_6979() -> None:
    for q_hex, x_hex, k_sample, k_test in RFC_6979:
        q, x = int(q_hex, 16), int(x_hex, 16)
        qlen = q.bit_length()
        octets = (qlen + 7) // 8
        for message, k_hex in ((b"sample", k_sample), (b"test", k_test)):
            h1 = int.from_bytes(hashlib.sha512(message).digest(), "big")
            if qlen < 512:
                h1 >>= 512 - qlen
            drbg = HmacDrbg(x.to_bytes(octets, "big"), (h1 % q).to_bytes(octets, "big"), b"")
            k = int.from_bytes(drbg.generate(octets, b""), "big") >> (8 * octets - qlen)
            if k != int(k_hex, 16):
                sys.exit(f"the reference does not reproduce RFC 6979's k for qlen {qlen}, {message!r}")


# --- the corpus


def stream(label: str, length: int) -> bytes:
    return hashlib.shake_256(label.encode()).digest(length)


def text(data: bytes) -> str:
    return data.hex() if data else "-"


def output(data: bytes) -> str:
    return "=" + data.hex() if len(data) <= 256 else "#" + hashlib.sha512(data).hexdigest()


class Case:
    """One case, printed as it is built."""

    def __init__(self, name: str, entropy: int = 32, nonce: int = 16, personalization: int = 0):
        self.name = name
        self.step = 0
        e = stream(f"{name} entropy", entropy)
        n = stream(f"{name} nonce", nonce)
        p = stream(f"{name} personalization", personalization)
        print(f"case {name}")
        print("i", text(e), text(n), text(p))
        self.drbg = HmacDrbg(e, n, p)

    def _label(self, what: str) -> str:
        self.step += 1
        return f"{self.name} step {self.step} {what}"

    def reseed(self, entropy: int = 32, additional: int = 0) -> None:
        e = stream(self._label("entropy"), entropy)
        a = stream(self._label("additional"), additional)
        print("r", text(e), text(a))
        self.drbg.reseed(e, a)

    def generate(self, length: int, additional: int = 0) -> None:
        a = stream(self._label("additional"), additional)
        print("g", length, text(a), output(self.drbg.generate(length, a)))

    def predict(self, length: int, entropy: int = 32, additional: int = 0) -> None:
        e = stream(self._label("entropy"), entropy)
        a = stream(self._label("additional"), additional)
        self.drbg.reseed(e, a)
        print("p", length, text(e), text(a), output(self.drbg.generate(length, b"")))


def main() -> None:
    check_rfc_6979()
    print("# HMAC_DRBG (SHA-512) differential corpus for origin-crypto. Generated by")
    print("# security/crypto/tools/hmac_drbg_reference.py, an independent implementation of")
    print("# SP 800-90A Rev. 1 section 10.1.2 over Python's hmac, after it reproduced RFC 6979's")
    print("# six SHA-512 nonces. The format is described at the top of that file.")

    # The three shapes NIST's validation vectors have (no reseed; a reseed; prediction
    # resistance), each with and without a personalization string and additional input, at the
    # shortest seed and at longer ones. Two requests of 256 bytes, as NIST's SHA-512 groups ask.
    for shape in ("plain", "reseed", "predict"):
        for personalization in (0, 32, 64):
            for additional in (0, 32, 64):
                for entropy, nonce in ((32, 16), (48, 24), (64, 32)):
                    case = Case(
                        f"{shape}-p{personalization}-a{additional}-e{entropy}",
                        entropy,
                        nonce,
                        personalization,
                    )
                    if shape == "reseed":
                        case.reseed(entropy, additional)
                    for _ in range(2):
                        if shape == "predict":
                            case.predict(256, entropy, additional)
                        else:
                            case.generate(256, additional)

    # Request lengths around the output block (64 bytes), none, and the most one request may
    # ask for (65536 bytes), from one instantiation, so each request starts from the state the
    # last one left.
    case = Case("request-lengths")
    for length in (0, 1, 2, 31, 32, 33, 63, 64, 65, 127, 128, 129, 191, 192, 193, 255, 256, 257, 1000, 4096, 65535, 65536):
        case.generate(length)
    case = Case("request-lengths-additional", personalization=17)
    for length in (0, 1, 63, 64, 65, 128, 129, 257, 65536):
        case.generate(length, additional=length % 97)

    # Input lengths around the boundaries of the HMAC that takes them. Its message is V (64
    # bytes), one byte and the input: the hash's length field stops fitting at an input of 46
    # and 47 bytes (and 174 and 175), and a block ends at 63 (and 191).
    lengths = (32, 33, 46, 47, 48, 62, 63, 64, 65, 110, 111, 112, 127, 128, 129, 174, 175, 176, 191, 192, 255, 256, 1024, 8192)
    for entropy in lengths:
        case = Case(f"entropy-{entropy}", entropy=entropy)
        case.generate(64)
        case.reseed(entropy=entropy)
        case.generate(64)
    for nonce in (16, 17, 31, 32, 46, 47, 63, 64, 128, 1024):
        case = Case(f"nonce-{nonce}", nonce=nonce)
        case.generate(64)
    for personalization in (1, 14, 15, 16, 31, 46, 47, 63, 64, 65, 200, 1024):
        case = Case(f"personalization-{personalization}", personalization=personalization)
        case.generate(64)
    for additional in (1, 2, 45, 46, 47, 48, 62, 63, 64, 65, 128, 174, 175, 300, 1024):
        case = Case(f"additional-{additional}")
        case.generate(64, additional)
        case.reseed(additional=additional)
        case.generate(64, additional)
        case.predict(64, additional=additional)

    # A long life: 400 requests of 8 bytes, which is what the kernel will mostly ask for, with a
    # reseed every 50, some additional input, and a request with prediction resistance now and
    # then.
    case = Case("long-life", entropy=64, nonce=32, personalization=24)
    for request in range(400):
        if request % 50 == 49:
            case.reseed(entropy=48, additional=request % 3 * 16)
        if request % 37 == 36:
            case.predict(8, additional=request % 5)
        else:
            case.generate(8, additional=(request % 7 == 0) * 20)


# --- the cross-check against an installed OpenSSL


class OsslParam(ctypes.Structure):
    """OpenSSL's OSSL_PARAM (openssl/core.h)."""

    _fields_ = [
        ("key", ctypes.c_char_p),
        ("data_type", ctypes.c_uint),
        ("data", ctypes.c_void_p),
        ("data_size", ctypes.c_size_t),
        ("return_size", ctypes.c_size_t),
    ]


UNSIGNED_INTEGER, UTF8_STRING, OCTET_STRING = 2, 4, 5


def params(*entries):
    """An OSSL_PARAM array, and the buffers it points into, which must outlive its use."""
    keep, array = [], (OsslParam * (len(entries) + 1))()
    for slot, (key, kind, value) in zip(array, entries):
        if kind == UNSIGNED_INTEGER:
            buffer = ctypes.c_uint(value)
            size = ctypes.sizeof(buffer)
        else:
            buffer = ctypes.create_string_buffer(value, len(value))
            size = len(value)
        keep.append(buffer)
        slot.key, slot.data_type, slot.data_size = key, kind, size
        slot.data = ctypes.cast(ctypes.pointer(buffer), ctypes.c_void_p)
    return array, keep


class OpensslDrbg:
    """OpenSSL's HMAC-DRBG over SHA-512, fed its entropy and nonce by OpenSSL's TEST-RAND."""

    def __init__(self, lib, entropy_input: bytes, nonce: bytes, personalization_string: bytes):
        self.lib = lib
        self.parent = self._new(b"TEST-RAND", None)
        self.drbg = self._new(b"HMAC-DRBG", self.parent)
        # No reseeding of OpenSSL's own accord: only the reseeds the corpus asks for.
        self._set(self.drbg, (b"digest", UTF8_STRING, b"SHA2-512"), (b"mac", UTF8_STRING, b"HMAC"),
                  (b"reseed_requests", UNSIGNED_INTEGER, 1 << 30))
        seed, keep = params((b"test_entropy", OCTET_STRING, entropy_input), (b"test_nonce", OCTET_STRING, nonce),
                            (b"strength", UNSIGNED_INTEGER, 256))
        self._ok(lib.EVP_RAND_instantiate(self.parent, 256, 0, None, 0, seed), "the test source")
        self._ok(lib.EVP_RAND_instantiate(self.drbg, 256, 0, personalization_string,
                                          len(personalization_string), None), "instantiate")

    def _new(self, name, parent):
        rand = self.lib.EVP_RAND_fetch(None, name, None)
        context = self.lib.EVP_RAND_CTX_new(rand, parent)
        if not rand or not context:
            sys.exit(f"this OpenSSL has no {name.decode()}")
        return context

    def _ok(self, result, what):
        if result != 1:
            sys.exit(f"OpenSSL refused: {what}")

    def _set(self, context, *entries):
        array, keep = params(*entries)
        self._ok(self.lib.EVP_RAND_CTX_set_params(context, array), "a parameter")

    def reseed(self, entropy_input: bytes, additional_input: bytes) -> None:
        self._set(self.parent, (b"test_entropy", OCTET_STRING, entropy_input))
        self._ok(self.lib.EVP_RAND_reseed(self.drbg, 0, None, 0, additional_input, len(additional_input)), "reseed")

    def generate(self, length: int, additional_input: bytes, fresh_entropy: bytes = None) -> bytes:
        if fresh_entropy is not None:
            self._set(self.parent, (b"test_entropy", OCTET_STRING, fresh_entropy))
        out = ctypes.create_string_buffer(length)
        self._ok(self.lib.EVP_RAND_generate(self.drbg, out, length, 256, int(fresh_entropy is not None),
                                            additional_input, len(additional_input)), "generate")
        return out.raw

    def free(self):
        self.lib.EVP_RAND_CTX_free(self.drbg)
        self.lib.EVP_RAND_CTX_free(self.parent)


def load(path: str):
    lib = ctypes.CDLL(path)
    pointer, size, integer, raw = ctypes.c_void_p, ctypes.c_size_t, ctypes.c_int, ctypes.c_char_p
    lib.EVP_RAND_fetch.restype, lib.EVP_RAND_fetch.argtypes = pointer, [pointer, raw, raw]
    lib.EVP_RAND_CTX_new.restype, lib.EVP_RAND_CTX_new.argtypes = pointer, [pointer, pointer]
    lib.EVP_RAND_CTX_free.restype, lib.EVP_RAND_CTX_free.argtypes = None, [pointer]
    lib.EVP_RAND_CTX_set_params.restype, lib.EVP_RAND_CTX_set_params.argtypes = integer, [pointer, pointer]
    lib.EVP_RAND_instantiate.restype = integer
    lib.EVP_RAND_instantiate.argtypes = [pointer, ctypes.c_uint, integer, raw, size, pointer]
    lib.EVP_RAND_reseed.restype = integer
    lib.EVP_RAND_reseed.argtypes = [pointer, integer, raw, size, raw, size]
    lib.EVP_RAND_generate.restype = integer
    lib.EVP_RAND_generate.argtypes = [pointer, raw, size, ctypes.c_uint, integer, raw, size]
    lib.OpenSSL_version.restype, lib.OpenSSL_version.argtypes = raw, [integer]
    return lib


def unhex(field: str) -> bytes:
    return b"" if field == "-" else bytes.fromhex(field)


def crosscheck(corpus_path: str, library_path: str) -> None:
    lib = load(library_path)
    cases, case = [], None
    for line in open(corpus_path, encoding="ascii"):
        fields = line.split()
        if not fields or fields[0] == "#":
            continue
        if fields[0] == "case":
            case = (fields[1], [])
            cases.append(case)
        else:
            case[1].append(fields)
    whole = cut = outputs = 0
    for name, steps in cases:
        # OpenSSL does not call its generator for no bytes, where the standard's steps still move
        # the state. A case with such a request is replayed without it on both sides.
        without = [step for step in steps if not (step[0] in "gp" and step[1] == "0")]
        direct = len(without) == len(steps)
        ours = theirs = None
        for step in without:
            if step[0] == "i":
                seed = [unhex(field) for field in step[1:4]]
                ours, theirs = HmacDrbg(*seed), OpensslDrbg(lib, *seed)
            elif step[0] == "r":
                ours.reseed(unhex(step[1]), unhex(step[2]))
                theirs.reseed(unhex(step[1]), unhex(step[2]))
            else:
                length = int(step[1])
                if step[0] == "g":
                    additional = unhex(step[2])
                    want = ours.generate(length, additional)
                    got = theirs.generate(length, additional)
                else:
                    entropy, additional = unhex(step[2]), unhex(step[3])
                    ours.reseed(entropy, additional)
                    want = ours.generate(length, b"")
                    got = theirs.generate(length, additional, fresh_entropy=entropy)
                if got != want:
                    sys.exit(f"OpenSSL and the reference differ in case {name}, a request of {length} bytes")
                if direct and output(got) != step[-1]:
                    sys.exit(f"OpenSSL and the corpus differ in case {name}, a request of {length} bytes")
                outputs += 1
        theirs.free()
        whole, cut = whole + direct, cut + (not direct)
    print(f"{lib.OpenSSL_version(0).decode()}: {whole} cases agree with the corpus line for line,")
    print(f"and {cut} more with the reference once their requests of no bytes are left out; {outputs} outputs compared")


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "crosscheck":
        check_rfc_6979()
        crosscheck(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 1:
        main()
    else:
        sys.exit(__doc__)
