#!/usr/bin/env python3
"""An independent HMAC_DRBG over SHA-512, and the differential corpus for origin-crypto.

The generator is NIST SP 800-90A Rev. 1 section 10.1.2, written here from the standard's
steps over Python's `hmac` (OpenSSL's HMAC). It shares no code with the Rust in
`src/hmac_drbg.rs` and is built differently: it holds the key itself and concatenates its
inputs, where the Rust holds two hash states and never builds the concatenation. It has the
same author, which is why `tests/kat` checks the Rust against NIST's own vectors as well.

Before it writes anything it must reproduce six published values: the nonces of RFC 6979
appendix A.2.5 to A.2.7 for SHA-512, which that RFC's section 3.3 defines as HMAC_DRBG output.

The corpus is a list of cases. A case is an instantiation and the requests made of it:

    case <name>
    i <entropy input> <nonce> <personalization string>     instantiate
    r <entropy input> <additional input>                    reseed
    g <bytes> <additional input> <output>                   generate
    p <bytes> <entropy input> <additional input> <output>   reseed, then generate with no
                                                            additional input (a request with
                                                            prediction resistance, 9.3.1)

Byte strings are hexadecimal, `-` for the empty string. An output of up to 256 bytes is `=`
and its bytes; a longer one is `#` and its SHA-512 digest. Inputs come from SHAKE-256 over the
case's name, so the file can be regenerated byte for byte.

Host-only engineering tool; nothing here ships.

Usage: python3 -I hmac_drbg_reference.py > ../tests/vectors/hmac-drbg-differential.txt
"""

import hashlib
import hmac
import sys

OUT = 64


class HmacDrbg:
    """SP 800-90A Rev. 1 section 10.1.2 over SHA-512."""

    def __init__(self, entropy_input: bytes, nonce: bytes, personalization_string: bytes):
        # 10.1.2.3: Key = 0x00 ... 00, V = 0x01 ... 01, then one update with the seed material.
        self.key = bytes(OUT)
        self.v = b"\x01" * OUT
        self._update(entropy_input + nonce + personalization_string)
        self.reseed_counter = 1

    def _hmac(self, data: bytes) -> bytes:
        return hmac.new(self.key, data, hashlib.sha512).digest()

    def _update(self, provided_data: bytes) -> None:
        # 10.1.2.2.
        self.key = self._hmac(self.v + b"\x00" + provided_data)
        self.v = self._hmac(self.v)
        if not provided_data:
            return
        self.key = self._hmac(self.v + b"\x01" + provided_data)
        self.v = self._hmac(self.v)

    def reseed(self, entropy_input: bytes, additional_input: bytes) -> None:
        # 10.1.2.4.
        self._update(entropy_input + additional_input)
        self.reseed_counter = 1

    def generate(self, length: int, additional_input: bytes) -> bytes:
        # 10.1.2.5, without step 1: the corpus never passes a reseed interval.
        if additional_input:
            self._update(additional_input)
        temp = b""
        while len(temp) < length:
            self.v = self._hmac(self.v)
            temp += self.v
        self._update(additional_input)
        self.reseed_counter += 1
        return temp[:length]


