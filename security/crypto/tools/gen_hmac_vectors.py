#!/usr/bin/env python3
"""Generate HMAC-SHA-512 differential test vectors for origin-crypto (CLAUDE.md §59).

Each vector is a deterministic key and message: byte i of a k-byte key is
(i * 17 + k * 3 + 5) mod 256, and byte i of an n-byte message is (i * 31 + n * 7 + 13) mod 256
(the message of gen_sha2_vectors.py). src/tests_hmac.rs rebuilds both.

Every MAC is computed two ways and written only if they agree:

- Python's `hmac` module (OpenSSL's HMAC, or the interpreter's own where OpenSSL lacks it);
- RFC 2104's formula written out here, H((K0 ^ opad) || H((K0 ^ ipad) || text)), over
  hashlib's SHA-512.

Host-only engineering tool; nothing here ships.

Usage: python3 -I gen_hmac_vectors.py > ../tests/vectors/hmac-sha512-differential.txt
"""

import hashlib
import hmac
import sys

BLOCK = 128

# Key lengths around the empty key, the digest length and the block length (a longer key is
# hashed first). Message lengths around the padding boundaries of the inner hash, whose first
# block is the key's: 111 and 112 bytes are where the length field stops fitting.
KEY_LENGTHS = [0, 1, 20, 63, 64, 65, 127, 128, 129, 131, 200, 256, 1000]
MESSAGE_LENGTHS = [0, 1, 2, 63, 64, 65, 110, 111, 112, 113, 127, 128, 129, 239, 240, 241, 255, 256, 257, 1000, 4096]


def key(k: int) -> bytes:
    return bytes((i * 17 + k * 3 + 5) & 0xFF for i in range(k))


def message(n: int) -> bytes:
    return bytes((i * 31 + n * 7 + 13) & 0xFF for i in range(n))


def by_definition(k: bytes, text: bytes) -> str:
    if len(k) > BLOCK:
        k = hashlib.sha512(k).digest()
    k0 = k + bytes(BLOCK - len(k))
    inner = hashlib.sha512(bytes(b ^ 0x36 for b in k0) + text).digest()
    return hashlib.sha512(bytes(b ^ 0x5C for b in k0) + inner).hexdigest()


def main() -> None:
    print("# HMAC-SHA-512 differential vectors for origin-crypto. Generated by")
    print("# security/crypto/tools/gen_hmac_vectors.py; Python's hmac module and RFC 2104's formula")
    print("# over hashlib's SHA-512 agreed on every line.")
    print("# Key k: byte i = (i * 17 + k * 3 + 5) mod 256. Message n: byte i = (i * 31 + n * 7 + 13) mod 256.")
    print("# Columns: key-length message-length hmac-sha512")
    for k in KEY_LENGTHS:
        for n in MESSAGE_LENGTHS:
            mac = hmac.new(key(k), message(n), hashlib.sha512).hexdigest()
            if by_definition(key(k), message(n)) != mac:
                sys.exit(f"reference implementations disagree at key {k}, message {n}")
            print(k, n, mac)


if __name__ == "__main__":
    main()
