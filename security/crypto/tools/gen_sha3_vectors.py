#!/usr/bin/env python3
"""Generate SHA-3/SHAKE differential test vectors for origin-crypto (CLAUDE.md §59).

Each vector hashes a deterministic message: byte i of the n-byte message is
(i * 31 + n * 7 + 13) mod 256, the same messages as gen_sha2_vectors.py. src/tests_sha3.rs
rebuilds them. The lengths 0..=300 cross every rate boundary (72, 136 and 168 bytes) and
their first multiples; 1000, 4096 and 65536 bytes add long multi-block messages.

Every output is computed by both of Python's SHA-3 implementations, hashlib's OpenSSL
backend (_hashlib) and its built-in HACL* backend (_sha3), and is written only if they
agree. Host-only engineering tool; nothing here ships.

Usage: python3 -I gen_sha3_vectors.py > ../tests/vectors/sha3-differential.txt
"""

import _sha3
import hashlib
import sys

LENGTHS = list(range(0, 301)) + [1000, 4096, 65536]
SHAKE_LEN = 200


def message(n: int) -> bytes:
    return bytes((i * 31 + n * 7 + 13) & 0xFF for i in range(n))


def outputs(module, m: bytes) -> list[str]:
    return [
        module.sha3_256(m).hexdigest(),
        module.sha3_512(m).hexdigest(),
        module.shake_128(m).hexdigest(SHAKE_LEN),
        module.shake_256(m).hexdigest(SHAKE_LEN),
    ]


def main() -> None:
    if type(hashlib.sha3_256()).__module__ != "_hashlib":
        sys.exit("hashlib.sha3_256 is not the OpenSSL backend; the two references would coincide")
    print("# SHA-3 differential vectors for origin-crypto. Generated by")
    print("# security/crypto/tools/gen_sha3_vectors.py; hashlib's OpenSSL and HACL* backends")
    print("# agreed on every line.")
    print("# Message n: byte i = (i * 31 + n * 7 + 13) mod 256.")
    print(f"# Columns: length sha3-256 sha3-512 shake128({SHAKE_LEN} bytes) shake256({SHAKE_LEN} bytes)")
    for n in LENGTHS:
        m = message(n)
        openssl = outputs(hashlib, m)
        if outputs(_sha3, m) != openssl:
            sys.exit(f"reference implementations disagree at length {n}")
        print(n, *openssl)


if __name__ == "__main__":
    main()
