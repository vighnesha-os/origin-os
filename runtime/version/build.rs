//! Generates the `origin-version` constants from the repository's `origin-version.toml`.
//!
//! The output depends only on that file: no timestamps, host paths or git state
//! (ONBF-R9, CLAUDE.md §75). An invalid file fails the build with the offending line.

mod manifest;

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    match generate() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn generate() -> Result<(), String> {
    let crate_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR is not set")?);
    let source = crate_dir.join("../../origin-version.toml");
    println!("cargo::rerun-if-changed={}", source.display());
    println!("cargo::rerun-if-changed=manifest.rs");

    let text = fs::read_to_string(&source).map_err(|e| format!("{}: {e}", source.display()))?;
    let m = manifest::parse(&text)?;

    let out = format!(
        "// Generated by runtime/version/build.rs from origin-version.toml. Do not edit.\n\
         \n\
         /// Release version, SemVer 2.0 (`[release] version`).\n\
         pub const VERSION: &str = {version:?};\n\
         /// SemVer major version.\n\
         pub const VERSION_MAJOR: u64 = {major};\n\
         /// SemVer minor version.\n\
         pub const VERSION_MINOR: u64 = {minor};\n\
         /// SemVer patch version.\n\
         pub const VERSION_PATCH: u64 = {patch};\n\
         /// SemVer pre-release identifiers; empty for a release version.\n\
         pub const VERSION_PRE: &str = {pre:?};\n\
         /// Monotonic build number of signed releases; 0 if never released (`[release] build`).\n\
         pub const BUILD: u64 = {build};\n\
         /// Anti-rollback security version number (`[release] security-version`).\n\
         pub const SECURITY_VERSION: u32 = {svn};\n\
         /// ONBF container `format_major` (`[compatibility] onbf-format`).\n\
         pub const ONBF_FORMAT_MAJOR: u16 = {fmaj};\n\
         /// ONBF container `format_minor` (`[compatibility] onbf-format`).\n\
         pub const ONBF_FORMAT_MINOR: u16 = {fmin};\n",
        version = m.version.text(),
        major = m.version.major,
        minor = m.version.minor,
        patch = m.version.patch,
        pre = m.version.pre,
        build = m.build,
        svn = m.security_version,
        fmaj = m.onbf_format.0,
        fmin = m.onbf_format.1,
    );

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?);
    write_if_changed(&out_dir.join("origin_version.rs"), &out)
}

/// Leaves the file untouched when the content is unchanged, so dependants do not rebuild.
fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if fs::read_to_string(path).is_ok_and(|old| old == content) {
        return Ok(());
    }
    fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))
}
