#!/usr/bin/env python3
"""Builds a signed ONBF signature block for the onbf-verify tests (S1-S4 encodings).

Signs with the independent pure-Python references in security/crypto/tools (Ed25519,
RFC 8032; ML-DSA-87, FIPS 204, deterministic). Deterministic keys and inputs, so the output
is byte-identical on every run:

    python3 -I runtime/onbf/verify/tools/make_fixture.py > runtime/onbf/verify/tests/vectors/kernel-block.txt
"""
import hashlib
import importlib.util
import pathlib
import sys

sys.dont_write_bytecode = True  # no __pycache__ next to the reference tools

TOOLS = pathlib.Path(__file__).resolve().parents[4] / "security" / "crypto" / "tools"


def load(name):
    spec = importlib.util.spec_from_file_location(name, TOOLS / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


ed = load("ed25519_reference")
ml = load("mldsa_reference")


def head(major, n):
    m = major << 5
    if n < 24:
        return bytes([m | n])
    if n < 0x100:
        return bytes([m | 24, n])
    if n < 0x10000:
        return bytes([m | 25]) + n.to_bytes(2, "big")
    return bytes([m | 26]) + n.to_bytes(4, "big")


def uint(n):
    return head(0, n)


def bstr(b):
    return head(2, len(b)) + b


def tstr(t):
    return head(3, len(t.encode())) + t.encode()


def cmap(entries):
    out = head(5, len(entries))
    for k, v in entries:
        out += uint(k) + v
    return out


ROLE_KERNEL, SUITE_OSS1R, PROFILE_KRN = 4, 2, 6
DIGEST = hashlib.sha512(b"origin onbf-verify fixture content").digest()

ed_seed = hashlib.sha256(b"origin fixture ed25519 key").digest()
ml_xi = hashlib.sha256(b"origin fixture ml-dsa-87 key").digest()
ed_pk = ed.public_key(ed_seed)
ml_pk, ml_sk = ml.keygen_internal(ml_xi, ml.ML_DSA_87)

# The canonical public-key encoding behind key_id (S4): the OCBOR `keys` map.
keys_map = cmap([(0, bstr(ed_pk)), (1, bstr(ml_pk))])
key_id = hashlib.sha256(keys_map).digest()

statement = cmap([
    (0, uint(1)),
    (1, uint(PROFILE_KRN)),
    (2, bstr(DIGEST)),
    (3, tstr("origin.framekernel")),
    (4, tstr("0.1.0-dev")),
    (5, uint(ROLE_KERNEL)),
    (6, uint(1_794_000_000)),
])
_, sig_ed = ed.sign(ed_seed, statement)
sig_ml = ml.sign(ml_sk, statement, b"origin/onbf/1/origin-kernel", ml.DETERMINISTIC, ml.ML_DSA_87)
assert ed.verify(ed_pk, statement, sig_ed) == "ok"
assert len(sig_ml) == 4627

entry = cmap([
    (1, uint(ROLE_KERNEL)),
    (2, uint(SUITE_OSS1R)),
    (3, bstr(key_id)),
    (4, head(4, 0)),  # no certificates: signed by a trusted key directly
    (5, statement),
    (6, bstr(sig_ed)),
    (7, bstr(sig_ml)),
])
block = b"ONBFSIG1" + (1).to_bytes(4, "little") + (1).to_bytes(4, "little")
block += len(entry).to_bytes(4, "little") + entry

print("# ONBF signature block fixture (Kernel role, OSS-1R); generated by tools/make_fixture.py")
print(f"digest {DIGEST.hex()}")
print(f"profile {PROFILE_KRN}")
print(f"ed25519_pk {ed_pk.hex()}")
print(f"mldsa87_pk {ml_pk.hex()}")
print(f"block {block.hex()}")
