#!/usr/bin/env bash
# Origin OS toolchain verification: CLAUDE.md §8, §9 and §10 (§84 steps 2-5).
#
#   bash developer-tools/toolchain/verify.sh            check only; installs nothing
#   bash developer-tools/toolchain/verify.sh --install  first add the pinned toolchain,
#                                                       components and targets with rustup
#   ... --report FILE                                   write the report to FILE instead of
#                                                       docs/toolchain/VERIFICATION.md (CI does,
#                                                       so a run leaves its checkout unchanged)
#
# Every result written to the report comes from a command this script ran on this machine.
# Exit status: 0 if no check failed, 1 if any failed, 2 on usage errors.
# Written for the bash 3.2 that ships with macOS; also runs on Linux bash.
#
# A compiler upgrade (CLAUDE.md §15) changes four places together: `channel` in
# rust-toolchain.toml, `rust-version` in Cargo.toml, EXPECTED below, and the commit in
# developer-tools/toolchain/rustc-commit-hash. This script fails until all four agree: it compares
# the first three as text, and the fourth with what the compiler reports.

set -u

EXPECTED="1.100.0"
TARGETS="x86_64-unknown-none x86_64-unknown-uefi x86_64-unknown-linux-gnu"
COMPONENTS="rustfmt clippy rust-src llvm-tools"

usage() { echo "usage: $0 [--install] [--report FILE]" >&2; exit 2; }

MODE="check"
REPORT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --install) MODE="install" ;;
    --report)
      [ $# -ge 2 ] && [ -n "$2" ] || usage
      REPORT="$2"; shift ;;
    *) usage ;;
  esac
  shift
done
# A relative FILE is relative to where the script was started, not to the repository.
case "$REPORT" in ""|/*) ;; *) REPORT="$PWD/$REPORT" ;; esac

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd) || exit 2
REPO=$(cd "$SCRIPT_DIR/../.." && pwd) || exit 2
TESTS="$REPO/tests/toolchain"
PIN_FILE="$SCRIPT_DIR/rustc-commit-hash"
if [ -z "$REPORT" ]; then REPORT="$REPO/docs/toolchain/VERIFICATION.md"; fi
WORK=$(mktemp -d "${TMPDIR:-/tmp}/origin-verify.XXXXXX") || exit 2
trap 'rm -rf "$WORK"' EXIT
cd "$REPO" || exit 2   # rustup reads rust-toolchain.toml from the current directory

# In check mode rustup must not download anything on its own.
if [ "$MODE" = "check" ]; then export RUSTUP_AUTO_INSTALL=0; fi

PASS=0; FAIL=0; INFO=0
BODY="$WORK/body.md"
: > "$BODY"

note() { printf '%s\n' "$*" >> "$BODY"; }

# record STATUS "title" [evidence-file]
record() {
  local status="$1" title="$2" evidence="${3:-}"
  case "$status" in
    PASS) PASS=$((PASS + 1)) ;;
    FAIL) FAIL=$((FAIL + 1)) ;;
    *)    INFO=$((INFO + 1)) ;;
  esac
  printf '%-4s  %s\n' "$status" "$title"
  note "### ${status}: ${title}"
  note ""
  if [ -n "$evidence" ] && [ -s "$evidence" ]; then
    note '```text'
    head -c 8000 "$evidence" >> "$BODY"
    note ""
    note '```'
    note ""
  fi
}

have() { command -v "$1" >/dev/null 2>&1; }
# hex FILE OFFSET LENGTH: bytes as lowercase hex, no spaces
hex() { od -An -tx1 -j "$2" -N "$3" "$1" 2>/dev/null | tr -d ' \n'; }
# u32le FILE OFFSET: little-endian u32 as decimal (od uses host byte order; supported hosts are little-endian)
u32le() { od -An -tu4 -j "$2" -N 4 "$1" 2>/dev/null | tr -d ' \n'; }

finish() {
  local stamp
  stamp=$(date -u +%Y-%m-%dT%H:%M:%SZ)
  mkdir -p "$(dirname "$REPORT")"
  {
    echo "# Toolchain verification"
    echo
    echo "Generated by \`developer-tools/toolchain/verify.sh\` (mode: $MODE) at $stamp."
    echo "Re-run the script rather than editing this file (CLAUDE.md §9)."
    echo
    echo "| Result | Count |"
    echo "|---|---|"
    echo "| PASS | $PASS |"
    echo "| FAIL | $FAIL |"
    echo "| INFO | $INFO |"
    echo
    cat "$BODY"
  } > "$REPORT"
  echo
  echo "PASS $PASS, FAIL $FAIL, INFO $INFO. Report: $REPORT"
  if [ "$FAIL" -eq 0 ]; then exit 0; else exit 1; fi
}

# ---------------------------------------------------------------- host and source revision
out="$WORK/host.txt"
{
  uname -srm
  if have sw_vers; then sw_vers; fi
  if have sysctl; then sysctl -n machdep.cpu.brand_string 2>/dev/null || true; fi
  if have git; then
    echo "git revision: $(git -C "$REPO" rev-parse --short HEAD 2>/dev/null || echo none)"
    echo "uncommitted paths: $(git -C "$REPO" status --porcelain 2>/dev/null | wc -l | tr -d ' ')"
  fi
} > "$out" 2>&1
record INFO "Host and source revision" "$out"

# ---------------------------------------------------------------- rustup
out="$WORK/rustup.txt"
if ! have rustup; then
  echo "rustup was not found on PATH." > "$out"
  record FAIL "rustup is installed" "$out"
  finish
fi
rustup --version > "$out" 2>&1
record INFO "rustup version" "$out"

if [ "$MODE" = "install" ]; then
  out="$WORK/install.txt"
  if rustup toolchain install "$EXPECTED" --profile minimal \
       --component "$(echo $COMPONENTS | tr ' ' ',')" \
       --target "$(echo $TARGETS | tr ' ' ',')" > "$out" 2>&1; then
    record PASS "rustup installed $EXPECTED with components [$COMPONENTS] and targets [$TARGETS]" "$out"
  else
    record FAIL "rustup installed $EXPECTED with components [$COMPONENTS] and targets [$TARGETS]" "$out"
  fi
fi

# The version is written in three places; an upgrade that changes one must change all three.
out="$WORK/pin.txt"
CHANNEL=$(sed -n 's/^channel = "\(.*\)"$/\1/p' "$REPO/rust-toolchain.toml" 2>/dev/null)
MSRV=$(sed -n 's/^rust-version = "\(.*\)"$/\1/p' "$REPO/Cargo.toml" 2>/dev/null)
{
  echo "rust-toolchain.toml, channel:    ${CHANNEL:-not found}"
  echo "Cargo.toml, rust-version:        ${MSRV:-not found}"
  echo "verify.sh, EXPECTED:             $EXPECTED"
} > "$out"
if [ "$CHANNEL" = "$EXPECTED" ] && [ "$MSRV" = "$EXPECTED" ]; then
  record PASS "The pin is written the same in rust-toolchain.toml, Cargo.toml and this script ($EXPECTED)" "$out"
else
  record FAIL "The pin is written the same in rust-toolchain.toml, Cargo.toml and this script" "$out"
fi

out="$WORK/active.txt"
rustup show active-toolchain > "$out" 2>&1
if grep -q "^${EXPECTED}-" "$out"; then
  record PASS "rust-toolchain.toml selects Rust $EXPECTED in this repository" "$out"
else
  record FAIL "rust-toolchain.toml selects Rust $EXPECTED in this repository" "$out"
fi

# ---------------------------------------------------------------- compiler and cargo (§9)
out="$WORK/rustc.txt"
if ! rustc --version --verbose > "$out" 2>&1; then
  record FAIL "rustc runs" "$out"
  finish
fi
HOST=$(sed -n 's/^host: //p' "$out")
RELEASE=$(sed -n 's/^release: //p' "$out")
if [ "$RELEASE" = "$EXPECTED" ]; then
  record PASS "rustc is $EXPECTED (host $HOST)" "$out"
else
  record FAIL "rustc is $EXPECTED (found ${RELEASE:-unknown}; host ${HOST:-unknown})" "$out"
fi

# The version alone does not name one build. The commit the compiler reports must be the pinned
# one (CLAUDE.md §8: an exact compiler). It is what the compiler says of itself: rustup's check of
# what it downloaded against the channel's manifest is the only check of the binary.
COMMIT=$(sed -n 's/^commit-hash: //p' "$WORK/rustc.txt")
out="$WORK/commit.txt"
PINNED=""
if [ -r "$PIN_FILE" ]; then PINNED=$(sed -e 's/#.*$//' "$PIN_FILE" | tr -d ' \t\r\n'); fi
{
  echo "pinned:   ${PINNED:-none} (developer-tools/toolchain/rustc-commit-hash)"
  echo "reported: ${COMMIT:-none} (rustc --version --verbose)"
} > "$out"
case "$PINNED" in *[!0-9a-f]*) PINNED_OK=0 ;; *) PINNED_OK=1 ;; esac
if [ "${#PINNED}" -ne 40 ]; then PINNED_OK=0; fi
if [ "$PINNED_OK" -ne 1 ]; then
  record FAIL "The pinned commit is 40 hexadecimal digits in developer-tools/toolchain/rustc-commit-hash" "$out"
elif [ "$COMMIT" = "$PINNED" ]; then
  record PASS "rustc reports the pinned commit ($PINNED)" "$out"
else
  record FAIL "rustc reports the pinned commit (pinned $PINNED, reported ${COMMIT:-none})" "$out"
fi

out="$WORK/cargo.txt"
cargo --version > "$out" 2>&1
if grep -q "^cargo ${EXPECTED} " "$out"; then
  record PASS "cargo is $EXPECTED" "$out"
else
  record FAIL "cargo is $EXPECTED" "$out"
fi

SYSROOT=$(rustc --print sysroot 2>/dev/null)
TOOLBIN="$SYSROOT/lib/rustlib/$HOST/bin"

out="$WORK/targets.txt"
rustup target list --installed > "$out" 2>&1
missing=""
for t in $TARGETS; do grep -qx "$t" "$out" || missing="$missing $t"; done
if [ -z "$missing" ]; then
  record PASS "Targets installed: $TARGETS" "$out"
else
  echo "missing:$missing (run with --install)" >> "$out"
  record FAIL "Targets installed: $TARGETS" "$out"
fi

out="$WORK/components.txt"
rustup component list --installed > "$out" 2>&1
missing=""
for c in $COMPONENTS; do grep -Eq "^${c}(-|\$)" "$out" || missing="$missing $c"; done
if [ -z "$missing" ]; then
  record PASS "Components installed: $COMPONENTS" "$out"
else
  echo "missing:$missing (run with --install)" >> "$out"
  record FAIL "Components installed: $COMPONENTS" "$out"
fi

out="$WORK/edition.txt"
printf 'pub fn edition_2024_ok() -> u32 { 2024 }\n' > "$WORK/edition.rs"
if rustc --edition 2024 --crate-type lib --crate-name edition_check \
     -o "$WORK/libedition_check.rlib" "$WORK/edition.rs" > "$out" 2>&1; then
  record PASS "Edition 2024 compiles" "$out"
else
  record FAIL "Edition 2024 compiles" "$out"
fi

out="$WORK/cc.txt"
if have cc; then cc --version > "$out" 2>&1; else echo "cc: not found" > "$out"; fi
record INFO "Host C compiler (Cargo uses it to link host-side tools)" "$out"

# ---------------------------------------------------------------- rust-lld (§10, #163947)
out="$WORK/lld.txt"
LLD="$TOOLBIN/rust-lld"
if [ ! -x "$LLD" ]; then
  echo "not found: $LLD" > "$out"
  record FAIL "rust-lld is present in the toolchain" "$out"
elif "$LLD" -flavor gnu --version > "$out" 2>&1; then
  record PASS "§10 rust-lld runs when invoked directly, without the rustup proxy (rust-lang/rust#163947)" "$out"
else
  record FAIL "§10 rust-lld runs when invoked directly, without the rustup proxy (rust-lang/rust#163947)" "$out"
fi

out="$WORK/none_direct.txt"
if "$SYSROOT/bin/rustc" --edition 2024 --target x86_64-unknown-none -C opt-level=3 -C codegen-units=1 \
     -o "$WORK/none_direct.elf" "$TESTS/none_smoke.rs" > "$out" 2>&1; then
  record PASS "§10 the toolchain's own rustc, run directly, links a freestanding image with rust-lld (#163947)" "$out"
else
  record FAIL "§10 the toolchain's own rustc, run directly, links a freestanding image with rust-lld (#163947)" "$out"
fi

# ---------------------------------------------------------------- freestanding x86-64 (§9)
out="$WORK/none.txt"
img="$WORK/none_smoke.elf"
if rustc --edition 2024 --target x86_64-unknown-none -C opt-level=3 -C codegen-units=1 \
     -o "$img" "$TESTS/none_smoke.rs" > "$out" 2>&1; then
  m=$(hex "$img" 0 4); cls=$(hex "$img" 4 1); dat=$(hex "$img" 5 1)
  typ=$(hex "$img" 16 2); mach=$(hex "$img" 18 2)
  echo "ELF: magic=$m class=$cls data=$dat e_type=$typ e_machine=$mach" >> "$out"
  if [ "$m" = "7f454c46" ] && [ "$cls" = "02" ] && [ "$dat" = "01" ] && [ "$mach" = "3e00" ]; then
    record PASS "Freestanding release build links (x86_64-unknown-none -> ELF64 little-endian x86-64)" "$out"
  else
    record FAIL "Freestanding release build has an unexpected ELF header" "$out"
  fi
else
  record FAIL "Freestanding release build links (x86_64-unknown-none)" "$out"
fi

# ---------------------------------------------------------------- UEFI (§9)
UEFI_FLAGS="--edition 2024 --target x86_64-unknown-uefi -C opt-level=3 -C codegen-units=1 -C panic=abort"
out="$WORK/uefi.txt"
img="$WORK/uefi_smoke.efi"
if rustc $UEFI_FLAGS -o "$img" "$TESTS/uefi_smoke.rs" > "$out" 2>&1; then
  mz=$(hex "$img" 0 2); peoff=$(u32le "$img" 60)
  pe=""; mach=""; magic=""; subsys=""
  case "$peoff" in ''|*[!0-9]*) peoff="" ;; esac
  if [ -n "$peoff" ]; then
    pe=$(hex "$img" "$peoff" 4)
    mach=$(hex "$img" $((peoff + 4)) 2)
    magic=$(hex "$img" $((peoff + 24)) 2)
    subsys=$(hex "$img" $((peoff + 92)) 2)
  fi
  echo "PE: mz=$mz pe_offset=$peoff signature=$pe machine=$mach optional_magic=$magic subsystem=$subsys" >> "$out"
  if [ "$mz" = "4d5a" ] && [ "$pe" = "50450000" ] && [ "$mach" = "6486" ] \
     && [ "$magic" = "0b02" ] && [ "$subsys" = "0a00" ]; then
    record PASS "UEFI release build links (x86_64-unknown-uefi -> PE32+ x86-64 EFI application)" "$out"
  else
    record FAIL "UEFI release build has an unexpected PE header" "$out"
  fi
else
  record FAIL "UEFI release build links (x86_64-unknown-uefi)" "$out"
fi

# ---------------------------------------------------------------- wcslen inside the loader (§10, #163614)
# The test is `char16_len` in the loader's library (boot/uefi/src/uefi.rs): a length loop over a
# NUL-terminated CHAR16 string, which nothing calls. The loader is built as a release builds it
# (no feature, the release profile, the flags of .cargo/config.toml, the committed lock file),
# from nothing, in this run's temporary directory.
#
# The loader linking is a test of #163614 only while two things hold, so both are checked on
# every run, before the link is trusted:
#   1. LLVM still turns the loop into a call to `wcslen`: the function's own code, in the
#      library's object, names `wcslen`.
#   2. That object reaches the link: the library is one object, which holds the loop beside
#      everything else the loader takes from its library. The linker resolves every symbol of
#      an object it loads, and only then drops what nothing calls. (Planted fault, recorded in
#      docs/engineering/SOURCE_PROVENANCE.md: with the loop replaced by a call to a symbol
#      nothing defines, the link fails with "undefined symbol".)
# If either stops holding, the link would pass and prove nothing: that is a FAIL here.
NM="$TOOLBIN/llvm-nm"
LLVM_OBJDUMP="$TOOLBIN/llvm-objdump"
LOADER_TARGET="$WORK/loader"
# RUSTFLAGS in the environment would replace the workspace's flags for the loader.
loader_cargo() {
  env -u RUSTFLAGS -u CARGO_ENCODED_RUSTFLAGS -u CARGO_BUILD_RUSTFLAGS -u CARGO_TARGET_DIR \
    cargo build --locked --release --target x86_64-unknown-uefi \
      --package origin-boot-uefi --target-dir "$LOADER_TARGET" "$@"
}

out="$WORK/wcslen_lib.txt"
why=""
if [ ! -x "$NM" ] || [ ! -x "$LLVM_OBJDUMP" ]; then
  echo "llvm-nm or llvm-objdump is missing from $TOOLBIN (the llvm-tools component)." > "$out"
  why="no llvm-tools to read the object with"
elif ! loader_cargo --lib > "$out" 2>&1; then
  why="the loader's library did not build"
else
  # The archive under the name Cargo gives a library it was asked to build: beside the
  # target's other outputs. Where Cargo keeps its own copy is no interface (Cargo 1.100.0
  # moved it), and this directory is new in every run, so the file can only be this build's.
  rlib="$LOADER_TARGET/x86_64-unknown-uefi/release/liborigin_boot_uefi.rlib"
  : > "$out"
  if [ ! -f "$rlib" ]; then
    echo "expected $rlib, which is not there" >> "$out"
    why="the loader's library was not found as one archive"
  else
    "$NM" "$rlib" > "$WORK/wcslen_nm.txt" 2> /dev/null
    objects=$(grep -c '\.o:$' "$WORK/wcslen_nm.txt")
    sym=$(sed -n 's/^[0-9a-fA-F]* T \(.*char16_len\)$/\1/p' "$WORK/wcslen_nm.txt")
    syms=$(printf '%s\n' "$sym" | grep -c .)
    {
      echo "objects in the loader's library: $objects"
      grep '\.o:$' "$WORK/wcslen_nm.txt"
      grep -E ' T .*char16_len$| U wcslen$' "$WORK/wcslen_nm.txt"
    } >> "$out"
    if [ "$objects" -ne 1 ]; then
      why="the loader's library is $objects objects, not one: the object that holds the loop may not reach the link"
    elif [ "$syms" -ne 1 ]; then
      why="the loader's library defines char16_len $syms times, not once"
    else
      "$LLVM_OBJDUMP" -d -r --no-show-raw-insn --disassemble-symbols="$sym" "$rlib" 2> /dev/null \
        | grep -v '^$' | grep -v 'file format' > "$WORK/wcslen_dis.txt"
      cat "$WORK/wcslen_dis.txt" >> "$out"
      if ! grep -Eq 'IMAGE_REL_AMD64_REL32[[:space:]]+wcslen$' "$WORK/wcslen_dis.txt"; then
        why="the code of char16_len names no wcslen: LLVM no longer makes the loop that call, or the function is no longer that loop"
      fi
    fi
  fi
fi
if [ -z "$why" ]; then
  record PASS "§10 wcslen: inside the loader's library, LLVM turned the CHAR16 length loop into a call to wcslen (#163614)" "$out"
else
  record FAIL "§10 wcslen: the loader no longer exercises #163614: $why" "$out"
fi

out="$WORK/wcslen_link.txt"
img="$LOADER_TARGET/x86_64-unknown-uefi/release/origin-boot.efi"
if loader_cargo --bin origin-boot > "$out" 2>&1; then
  mz=$(hex "$img" 0 2); peoff=$(u32le "$img" 60)
  pe=""; mach=""; magic=""; subsys=""
  case "$peoff" in ''|*[!0-9]*) peoff="" ;; esac
  if [ -n "$peoff" ]; then
    pe=$(hex "$img" "$peoff" 4)
    mach=$(hex "$img" $((peoff + 4)) 2)
    magic=$(hex "$img" $((peoff + 24)) 2)
    subsys=$(hex "$img" $((peoff + 92)) 2)
  fi
  {
    echo "cargo build --locked --release --target x86_64-unknown-uefi --package origin-boot-uefi --bin origin-boot"
    echo "PE: mz=$mz pe_offset=$peoff signature=$pe machine=$mach optional_magic=$magic subsystem=$subsys"
  } > "$out"
  if [ "$mz" != "4d5a" ] || [ "$pe" != "50450000" ] || [ "$mach" != "6486" ] \
     || [ "$magic" != "0b02" ] || [ "$subsys" != "0a00" ]; then
    record FAIL "§10 wcslen: the loader linked, with an unexpected PE header" "$out"
  elif [ -z "$why" ]; then
    record PASS "§10 wcslen: the loader links with that call in its library (origin-boot.efi, PE32+ x86-64 EFI application) (#163614)" "$out"
  else
    record INFO "§10 wcslen: the loader links, which shows nothing about #163614 in this run (see the FAIL above)" "$out"
  fi
else
  # The linker's own lines, without the argument list rustc prints around them.
  grep -E 'error|undefined symbol|referenced by' "$out" | cut -c1-400 | head -20 > "$WORK/wcslen_link_short.txt"
  record FAIL "§10 wcslen: the loader did not build and link (#163614 if the linker names wcslen)" "$WORK/wcslen_link_short.txt"
fi

# ---------------------------------------------------------------- FFI bool (§10, #163911)
OBJDUMP="$TOOLBIN/llvm-objdump"; OBJDUMP_KIND="llvm"
if [ ! -x "$OBJDUMP" ]; then
  if have llvm-objdump; then OBJDUMP="llvm-objdump"
  elif have objdump && objdump --version 2>/dev/null | grep -q LLVM; then OBJDUMP="objdump"
  elif have objdump; then OBJDUMP="objdump"; OBJDUMP_KIND="gnu"
  else OBJDUMP=""; fi
fi
for t in $TARGETS; do
  out="$WORK/ffi_bool_$t.txt"
  obj="$WORK/ffi_bool_$t.o"
  if ! rustc --edition 2024 --crate-type lib --target "$t" -C opt-level=3 --emit obj \
       -o "$obj" "$TESTS/ffi_bool.rs" > "$out" 2>&1; then
    record FAIL "§10 FFI bool on $t: could not compile" "$out"
    continue
  fi
  if [ -z "$OBJDUMP" ]; then
    echo "No disassembler found; install the llvm-tools component." >> "$out"
    record FAIL "§10 FFI bool on $t: no disassembler" "$out"
    continue
  fi
  if [ "$OBJDUMP_KIND" = "gnu" ]; then
    "$OBJDUMP" -d --no-show-raw-insn --disassemble=rust_fn_returning_bool "$obj" >> "$out" 2>&1
  else
    "$OBJDUMP" -d --no-show-raw-insn --disassemble-symbols=rust_fn_returning_bool "$obj" >> "$out" 2>&1
  fi
  if grep -Eiq 'and[bwlq]?[[:space:]]+\$0x1,|set[a-z]+[[:space:]]+%' "$out"; then
    record PASS "§10 FFI bool return is reduced to 0 or 1 before returning on $t (#163911)" "$out"
  else
    record FAIL "§10 FFI bool return is reduced to 0 or 1 before returning on $t (#163911)" "$out"
  fi
done

# ---------------------------------------------------------------- float ABI (research E2; CLAUDE.md §11)
out="$WORK/float_none.txt"
if rustc --edition 2024 --crate-type lib --target x86_64-unknown-none -C opt-level=3 --emit asm \
     -o "$WORK/float_none.s" "$TESTS/float_abi.rs" > "$out" 2>&1; then
  grep -A8 '^scale:' "$WORK/float_none.s" >> "$out"
  if grep -q '__muldf3' "$WORK/float_none.s"; then
    record PASS "x86_64-unknown-none is soft-float: an f64 multiply calls __muldf3 (why §11 keeps userspace off this target)" "$out"
  else
    record FAIL "x86_64-unknown-none no longer calls __muldf3: revisit CLAUDE.md §11" "$out"
  fi
else
  record FAIL "Float ABI probe for x86_64-unknown-none: could not compile" "$out"
fi

out="$WORK/float_gnu.txt"
if rustc --edition 2024 --crate-type lib --target x86_64-unknown-linux-gnu -C opt-level=3 \
     -C target-cpu=x86-64-v3 --emit asm -o "$WORK/float_gnu.s" "$TESTS/float_abi.rs" > "$out" 2>&1; then
  grep -A8 '^scale:' "$WORK/float_gnu.s" >> "$out"
  if grep -q 'vmulsd' "$WORK/float_gnu.s"; then
    record PASS "Userspace code generation (x86_64-unknown-linux-gnu, x86-64-v3) uses hardware floating point (vmulsd)" "$out"
  else
    record FAIL "Userspace code generation did not use vmulsd: revisit CLAUDE.md §11" "$out"
  fi
else
  record FAIL "Float ABI probe for x86_64-unknown-linux-gnu: could not compile" "$out"
fi

# ---------------------------------------------------------------- hardening flags (CLAUDE.md §14)
out="$WORK/cflags.txt"
rustc -C help > "$WORK/chelp.txt" 2>&1
if grep -Eq 'cf-protection|stack-protector' "$WORK/chelp.txt"; then
  grep -E 'cf-protection|stack-protector' "$WORK/chelp.txt" > "$out"
  record INFO "cf-protection or stack-protector is now a stable -C option on ${RELEASE:-?}: update CLAUDE.md §14 and ONBF §6.1.3" "$out"
else
  echo "Neither cf-protection nor stack-protector appears in 'rustc -C help'." > "$out"
  record PASS "IBT (cf-protection) and stack-protector are still unstable on ${RELEASE:-?}, as CLAUDE.md §14 records" "$out"
fi

# ---------------------------------------------------------------- QEMU and firmware (needed from M1)
out="$WORK/qemu.txt"
{
  if have qemu-system-x86_64; then qemu-system-x86_64 --version | head -1
  else echo "qemu-system-x86_64: not installed"; fi
  # Homebrew's x86-64 firmware descriptors pair edk2-x86_64-*code.fd with the edk2-i386-vars.fd NVRAM template.
  for d in "$(brew --prefix 2>/dev/null)/share/qemu" /opt/homebrew/share/qemu /usr/local/share/qemu /usr/share/qemu /usr/share/OVMF; do
    if [ -d "$d" ]; then
      (cd "$d" && ls 2>/dev/null | grep -Ei 'edk2-x86_64|edk2-i386-vars|OVMF' | sed "s|^|$(pwd -P)/|")
    fi
  done | sort -u | while read -r f; do
    if have shasum; then shasum -a 256 "$f"; elif have sha256sum; then sha256sum "$f"; else echo "$f"; fi
  done
} > "$out" 2>&1
record INFO "QEMU and x86-64 UEFI firmware (needed from M1; install separately)" "$out"

