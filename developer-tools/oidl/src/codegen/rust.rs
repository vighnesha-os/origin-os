fn decoded_ty(g: &Gen<'_>, p: &Param, later: bool) -> String {
    let inner = match &p.ty {
        Type::Handle(h) => {
            if h.optional {
                "Option<rt::RecvHandle>".to_string()
            } else {
                "rt::RecvHandle".to_string()
            }
        }
        Type::Vector(elem, _) => match elem.as_ref() {
            Type::Handle(_) => "&'a [rt::RecvHandle]".to_string(),
            other => format!("rt::View<'a, {}>", g.fixed(3, other)),
        },
        Type::String(_) => "&'a str".to_string(),
        other => g.fixed(3, other),
    };
    if later {
        format!("Option<{inner}>")
    } else {
        inner
    }
}

fn args_ty(g: &Gen<'_>, p: &Param, later: bool) -> String {
    let inner = match &p.ty {
        Type::Handle(h) => {
            if h.optional {
                "Option<rt::Handle>".to_string()
            } else {
                "rt::Handle".to_string()
            }
        }
        Type::Vector(elem, _) => match elem.as_ref() {
            Type::Handle(_) => "&'r [rt::Handle]".to_string(),
            other => format!("&'r [{}]", g.fixed(3, other)),
        },
        Type::String(_) => "&'r str".to_string(),
        other => g.fixed(3, other),
    };
    if later {
        format!("Option<{inner}>")
    } else {
        inner
    }
}

fn gen_message_struct(
    g: &Gen<'_>,
    t: &mut Text,
    method: &Method,
    params: &[Param],
    name: &str,
    what: &str,
) {
    let borrows = has_borrow(params);
    let lifetime = if borrows { "<'a>" } else { "" };
    t.line(format!("/// A decoded {what} of `{}`.", method.name));
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.open(format!("pub struct {name}{lifetime} {{"));
    for param in params {
        t.doc(&param.doc);
        t.line(format!(
            "pub {}: {},",
            param.name,
            decoded_ty(g, param, param.since > method.since)
        ));
    }
    t.shut("}");
    t.blank();
    let args_lifetime = if borrows { "<'r>" } else { "" };
    t.line(format!(
        "/// The fields to encode a {what} of `{}`.",
        method.name
    ));
    t.line("#[derive(Clone, Copy, Debug)]");
    t.open(format!("pub struct {name}Args{args_lifetime} {{"));
    for param in params {
        t.doc(&param.doc);
        t.line(format!(
            "pub {}: {},",
            param.name,
            args_ty(g, param, param.since > method.since)
        ));
    }
    t.shut("}");
    t.blank();
    gen_decode(g, t, method, params, name, borrows);
    gen_encode(g, t, method, params, name, borrows);
}

fn gen_inline_size(t: &mut Text, params: &[Param], method_since: u16) {
    t.line("/// The inline part's size at `oidl_minor`.");
    t.open("pub const fn inline_size(oidl_minor: u16) -> usize {");
    let later: Vec<u16> = groups(params)
        .into_iter()
        .filter(|minor| *minor > method_since)
        .collect();
    let at_base = layout::message_layout(params, method_since).inline_size;
    if later.is_empty() {
        t.line("let _ = oidl_minor;");
        t.line(format!("{at_base}"));
    } else {
        t.line(format!("let mut size = {at_base};"));
        for minor in &later {
            t.line(format!(
                "if oidl_minor >= {minor} {{ size = {}; }}",
                layout::message_layout(params, *minor).inline_size
            ));
        }
        t.line("size");
    }
    t.shut("}");
}

/// The handle object and rights constants for a decoded slot.
fn handle_needs(p: &Param) -> (u64, u64) {
    match &p.ty {
        Type::Handle(h) => (h.object_value, h.rights_mask),
        Type::Vector(elem, _) => match elem.as_ref() {
            Type::Handle(h) => (h.object_value, h.rights_mask),
            _ => (0, 0),
        },
        _ => (0, 0),
    }
}

fn gen_decode(
    g: &Gen<'_>,
    t: &mut Text,
    method: &Method,
    params: &[Param],
    name: &str,
    borrows: bool,
) {
    let lifetime = if borrows { "<'a>" } else { "" };
    t.open(format!("impl{lifetime} {name}{lifetime} {{"));
    gen_inline_size(t, params, method.since.minor);
    t.blank();
    let signature = if borrows {
        "pub fn decode(oidl_body: &'a [u8], oidl_handles: &mut rt::HandleList<'a>, oidl_minor: u16) -> Result<Self, rt::WireError> {"
    } else {
        "pub fn decode<'a>(oidl_body: &'a [u8], oidl_handles: &mut rt::HandleList<'a>, oidl_minor: u16) -> Result<Self, rt::WireError> {"
    };
    t.line("/// Decodes and validates this message's body at the negotiated minor (§7.5).");
    t.open(signature);
    t.line("let _ = oidl_minor;");
    let binding = if has_borrow(params) {
        "let mut oidl_r"
    } else {
        "let oidl_r"
    };
    t.line(format!(
        "{binding} = rt::Reader::new(oidl_body, Self::inline_size(oidl_minor))?;"
    ));

    let minors = groups(params);
    let mut previous_inline = 0u64;
    for minor in &minors {
        let layout = layout::message_layout(params, *minor);
        // A parameter added after its method is absent at the method's own minor (§9).
        let conditional = *minor > method.since.minor;
        let later_names: Vec<&Param> = params.iter().filter(|p| p.since.minor == *minor).collect();
        if conditional {
            let binds: Vec<String> = later_names
                .iter()
                .map(|p| match p.ty {
                    Type::Vector(..) | Type::String(_) => format!("oidl_count_{}", p.name),
                    _ => p.name.clone(),
                })
                .collect();
            let lets = if binds.len() == 1 {
                binds.first().cloned().unwrap_or_default()
            } else {
                format!("({})", binds.join(", "))
            };
            t.open(format!("let {lets} = if oidl_minor >= {minor} {{"));
        }
        let mut steps: Vec<(u64, Step2)> = layout
            .placed
            .iter()
            .filter(|p| params.get(p.param).is_some_and(|q| q.since.minor == *minor))
            .map(|p| (p.offset, Step2::Param(p.param, p.kind)))
            .collect();
        steps.extend(
            layout
                .padding
                .iter()
                .filter(|(at, _)| *at >= previous_inline)
                .map(|(at, len)| (*at, Step2::Pad(*at, *len))),
        );
        steps.sort_by_key(|(at, _)| *at);
        for (at, step) in steps {
            match step {
                Step2::Pad(pad_at, len) => {
                    t.line(format!("oidl_r.zero({pad_at}, {len})?;"));
                }
                Step2::Param(index, kind) => {
                    let Some(param) = params.get(index) else {
                        continue;
                    };
                    gen_decode_inline(g, t, param, at, kind);
                }
            }
        }
        if conditional {
            let parts: Vec<String> = later_names
                .iter()
                .map(|p| match p.ty {
                    Type::Vector(..) | Type::String(_) => format!("oidl_count_{}", p.name),
                    _ => format!("Some({})", p.name),
                })
                .collect();
            let nones: Vec<String> = later_names
                .iter()
                .map(|p| match p.ty {
                    Type::Vector(..) | Type::String(_) => "0".to_string(),
                    _ => "None".to_string(),
                })
                .collect();
            let tuple = |list: &[String]| {
                if list.len() == 1 {
                    list.first().cloned().unwrap_or_default()
                } else {
                    format!("({})", list.join(", "))
                }
            };
            t.line(tuple(&parts));
            t.reopen("} else {");
            t.line(tuple(&nones));
            t.shut("};");
        }
        previous_inline = layout.inline_size;
    }
    // Exact size.
    let variable: Vec<&Param> = params
        .iter()
        .filter(|p| matches!(p.ty, Type::Vector(..) | Type::String(_)))
        .collect();
    let parts: Vec<String> = variable
        .iter()
        .map(|p| format!("(oidl_count_{}, {})", p.name, layout::element_size(&p.ty)))
        .collect();
    t.line(format!(
        "oidl_r.expect_total(rt::variable_size(&[{}]))?;",
        parts.join(", ")
    ));
    // Variable part.
    for param in &variable {
        let later = param.since > method.since;
        let expr = match &param.ty {
            Type::String(_) => format!("oidl_r.string(oidl_count_{})?", param.name),
            Type::Vector(elem, _) => match elem.as_ref() {
                Type::Handle(_) => {
                    let (object, rights) = handle_needs(param);
                    format!(
                        "oidl_r.handles(oidl_count_{}, oidl_handles, {object}, {rights:#x})?",
                        param.name
                    )
                }
                other => format!(
                    "oidl_r.vector::<{}>(oidl_count_{}, {})?",
                    g.fixed(3, other),
                    param.name,
                    Gen::minor_arg(other, &g.lib.name, "oidl_minor")
                ),
            },
            _ => "()".to_string(),
        };
        if later {
            t.line(format!(
                "let {name} = if oidl_minor >= {minor} {{ Some({expr}) }} else {{ None }};",
                name = param.name,
                minor = param.since.minor
            ));
        } else {
            t.line(format!("let {} = {expr};", param.name));
        }
    }
    t.line("oidl_handles.finish()?;");
    let fields: Vec<&str> = params.iter().map(|p| p.name.as_str()).collect();
    t.line(format!("Ok(Self {{ {} }})", fields.join(", ")));
    t.shut("}");
    t.shut("}");
    t.blank();
}

enum Step2 {
    Param(usize, InlineKind),
    Pad(u64, u64),
}

fn gen_decode_inline(g: &Gen<'_>, t: &mut Text, param: &Param, at: u64, kind: InlineKind) {
    match kind {
        InlineKind::Fixed => {
            let ty = g.fixed(3, &param.ty);
            t.line(format!(
                "let {name}: {ty} = oidl_r.field({at}, {minor})?;",
                name = param.name,
                minor = Gen::minor_arg(&param.ty, &g.lib.name, "oidl_minor")
            ));
            if param.nonzero {
                let zero = match &param.ty {
                    Type::Bits(_) => format!("{}.bits() == 0", param.name),
                    _ => format!("{} == 0", param.name),
                };
                t.open(format!("if {zero} {{"));
                t.line("return Err(rt::WireError::Nonzero);");
                t.shut("}");
            }
        }
        InlineKind::Count => {
            let bound = match &param.ty {
                Type::Vector(_, bound) | Type::String(bound) => *bound,
                _ => 0,
            };
            t.line(format!(
                "let oidl_count_{name} = oidl_r.count({at}, {bound})?;",
                name = param.name
            ));
        }
        InlineKind::Slot => {
            let (object, rights) = handle_needs(param);
            t.line(format!(
                "let oidl_slot_{name}: u32 = oidl_r.field({at}, 0)?;",
                name = param.name
            ));
            let optional = matches!(&param.ty, Type::Handle(h) if h.optional);
            if optional {
                t.line(format!(
                    "let {name} = oidl_handles.take_optional(oidl_slot_{name}, {object}, {rights:#x})?;",
                    name = param.name
                ));
            } else {
                t.line(format!(
                    "let {name} = oidl_handles.take(oidl_slot_{name}, {object}, {rights:#x})?;",
                    name = param.name
                ));
            }
        }
    }
}

fn gen_encode(
    g: &Gen<'_>,
    t: &mut Text,
    method: &Method,
    params: &[Param],
    name: &str,
    borrows: bool,
) {
    let lifetime = if borrows { "<'_>" } else { "" };
    t.open(format!("impl {name}Args{lifetime} {{"));
    t.line("/// Encodes this message's body at the negotiated minor, returning its size.");
    t.open("pub fn encode(&self, oidl_out: &mut [u8], oidl_handles: &mut rt::HandleSink<'_>, oidl_minor: u16) -> Result<usize, rt::WireError> {");
    t.line("let _ = (&oidl_handles, oidl_minor);");
    let writer = if params.is_empty() {
        "let oidl_w"
    } else {
        "let mut oidl_w"
    };
    t.line(format!(
        "{writer} = rt::Writer::new(oidl_out, {name}::inline_size(oidl_minor))?;"
    ));
    let newest = params.iter().map(|p| p.since.minor).max().unwrap_or(0);
    let layout = layout::message_layout(params, newest);
    for placed in &layout.placed {
        let Some(param) = params.get(placed.param) else {
            continue;
        };
        let later = param.since > method.since;
        let access = format!("self.{}", param.name);
        let body = |t: &mut Text, value: &str| match placed.kind {
            InlineKind::Fixed => {
                t.line(format!("oidl_w.put({}, {value})?;", placed.offset));
            }
            InlineKind::Count => {
                let bound = match &param.ty {
                    Type::Vector(_, bound) | Type::String(bound) => *bound,
                    _ => 0,
                };
                t.line(format!(
                    "oidl_w.count({}, {value}.len(), {bound})?;",
                    placed.offset
                ));
            }
            InlineKind::Slot => {
                let optional = matches!(&param.ty, Type::Handle(h) if h.optional);
                if optional {
                    t.open(format!("match {value} {{"));
                    t.line(format!(
                        "Some(oidl_h) => oidl_w.put({}, oidl_handles.put(oidl_h)?)?,",
                        placed.offset
                    ));
                    t.line(format!(
                        "None => oidl_w.put({}, rt::ABSENT_SLOT)?,",
                        placed.offset
                    ));
                    t.shut("}");
                } else {
                    t.line(format!(
                        "oidl_w.put({}, oidl_handles.put({value})?)?;",
                        placed.offset
                    ));
                }
            }
        };
        if later {
            t.open(format!(
                "if oidl_minor >= {minor} {{",
                minor = param.since.minor
            ));
            t.line(format!(
                "let oidl_v = {access}.ok_or(rt::WireError::Missing)?;"
            ));
            body(t, "oidl_v");
            t.shut("}");
        } else {
            body(t, &access);
        }
    }
    for param in params {
        if !matches!(param.ty, Type::Vector(..) | Type::String(_)) {
            continue;
        }
        let later = param.since > method.since;
        let access = format!("self.{}", param.name);
        let write = |value: &str| match &param.ty {
            Type::String(_) => format!("oidl_w.string({value})?;"),
            Type::Vector(elem, _) => match elem.as_ref() {
                Type::Handle(_) => format!("oidl_w.handles({value}, oidl_handles)?;"),
                other => format!("oidl_w.vector::<{}>({value})?;", g.fixed(3, other)),
            },
            _ => String::new(),
        };
        if later {
            t.open(format!(
                "if oidl_minor >= {minor} {{",
                minor = param.since.minor
            ));
            t.line(format!(
                "let oidl_v = {access}.ok_or(rt::WireError::Missing)?;"
            ));
            t.line(write("oidl_v"));
            t.shut("}");
        } else {
            t.line(write(&access));
        }
    }
    t.line("Ok(oidl_w.size())");
    t.shut("}");
    t.shut("}");
    t.blank();
}

fn gen_channel_server(g: &Gen<'_>, interface: &Interface) -> String {
    let mut t = Text::default();
    let status = g.status_path(3);
    let trait_name = format!("{}Server", pascal(&interface.name));
    t.line("//! Channel side of the interface: message codecs, per-method errors, the server trait and");
    t.line("//! the validating dispatcher (§7).");
    t.line(SAFE_ATTRS.trim_end());
    t.blank();
    t.line(format!("use {} as rt;", Gen::rt(3)));
    t.line("#[allow(unused_imports)]");
    t.line("use super::super::types::*;");
    t.blank();
    t.line("/// The interface's identity on the wire (§7.7).");
    t.line(format!(
        "pub const INTERFACE_ID: u64 = {:#x};",
        crate::fingerprint::interface_id(&g.lib.name, &interface.name)
    ));
    t.blank();
    t.line("/// Method ordinals (§7.1).");
    t.open("pub mod ordinal {");
    for method in &interface.methods {
        t.line(format!("/// `{}`.", method.name));
        t.line(format!(
            "pub const {}: u32 = {};",
            shouty(&method.name),
            method.ordinal
        ));
    }
    t.shut("}");
    t.blank();
    for method in &interface.methods {
        gen_method_error(g, &mut t, method);
        let base_name = pascal(&method.name);
        gen_message_struct(
            g,
            &mut t,
            method,
            &method.params,
            &format!("{base_name}Request"),
            "request",
        );
        if !method.oneway {
            gen_message_struct(
                g,
                &mut t,
                method,
                &method.returns,
                &format!("{base_name}Response"),
                "response",
            );
        }
    }
    t.line("/// The service's implementation of the interface.");
    t.open(format!("pub trait {trait_name} {{"));
    t.line("/// Who is calling, from the transport (ADR-0005 B1).");
    t.line("type Caller;");
    t.line("/// Whether this caller holds this capability on this connection (§6).");
    if g.lib.capabilities.is_empty() {
        t.line("fn holds(&self, caller: &Self::Caller) -> bool {");
        t.line("    let _ = caller;");
        t.line("    true");
        t.line("}");
    } else {
        t.line("fn holds(&self, caller: &Self::Caller, capability: Capability) -> bool;");
    }
    for method in &interface.methods {
        let base_name = pascal(&method.name);
        t.doc(&method.doc);
        let request_ty = format!(
            "{base_name}Request{}",
            if has_borrow(&method.params) {
                "<'_>"
            } else {
                ""
            }
        );
        if method.oneway {
            t.line(format!(
                "fn {}(&mut self, caller: &Self::Caller, request: {request_ty});",
                method.name
            ));
        } else {
            let response = if method.returns.is_empty() {
                format!("{base_name}ResponseArgs")
            } else {
                format!(
                    "{base_name}ResponseArgs{}",
                    if has_borrow(&method.returns) {
                        "<'_>"
                    } else {
                        ""
                    }
                )
            };
            t.line(format!(
                "fn {}(&mut self, caller: &Self::Caller, request: {request_ty}) -> Result<{response}, {base_name}Error>;",
                method.name
            ));
        }
    }
    t.shut("}");
    t.blank();

    // Dispatch.
    t.line("/// Validates and runs one message on a connection (§7.5, §7.8).");
    t.open(format!(
        "pub fn dispatch<S: {trait_name}>(server: &mut S, caller: &S::Caller, connection: &mut rt::Connection, message: &[u8], handles: &[rt::RecvHandle], reply: &mut [u8], reply_handles: &mut [u32]) -> rt::Dispatched {{"
    ));
    t.line("let Ok(oidl_header) = rt::read_header(message) else {");
    t.line("    return rt::Dispatched::Close { taken: false };");
    t.line("};");
    t.open("if oidl_header.kind != rt::KIND_REQUEST {");
    t.line("return rt::Dispatched::Close { taken: false };");
    t.shut("}");
    t.line("let oidl_body = message.get(rt::HEADER_SIZE..).unwrap_or(&[]);");
    t.open("if oidl_header.ordinal == rt::HELLO_ORDINAL {");
    t.line(format!(
        "let oidl_config = rt::HelloConfig {{ interface_id: INTERFACE_ID, major: VERSION.0, minor: VERSION.1, not_supported: {status}::NotSupported.raw() }};"
    ));
    t.line(
        "return rt::answer_hello(connection, oidl_header, oidl_body, handles, oidl_config, reply);",
    );
    t.shut("}");
    t.open("let Some(oidl_minor) = connection.negotiated() else {");
    t.line("return rt::Dispatched::Close { taken: false };");
    t.shut("};");
    t.open("match oidl_header.ordinal {");
    for method in &interface.methods {
        t.open(format!("ordinal::{} => {{", shouty(&method.name)));
        // §7.5: the transaction-id rule comes before the version check.
        let txid_bad = if method.oneway {
            "oidl_header.txid != 0"
        } else {
            "oidl_header.txid == 0"
        };
        t.open(format!("if {txid_bad} {{"));
        t.line("return rt::Dispatched::Close { taken: false };");
        t.shut("}");
        if method.since.minor > 0 {
            t.open(format!("if oidl_minor < {} {{", method.since.minor));
            t.line(format!(
                "return rt::refuse(reply, oidl_header.ordinal, oidl_header.txid, {status}::NotSupported.raw());"
            ));
            t.shut("}");
        }
        t.line(format!(
            "handle_{}(server, caller, oidl_header, oidl_body, handles, oidl_minor, reply, reply_handles)",
            method.name
        ));
        t.shut("}");
    }
    t.line(format!(
        "_ => rt::refuse(reply, oidl_header.ordinal, oidl_header.txid, {status}::NotSupported.raw()),"
    ));
    t.shut("}");
    t.shut("}");
    t.blank();
    for method in &interface.methods {
        gen_channel_handler(&mut t, method, &trait_name, &status);
    }
    t.finish()
}

fn gen_channel_handler(t: &mut Text, method: &Method, trait_name: &str, status: &str) {
    let base_name = pascal(&method.name);
    t.line("#[allow(clippy::too_many_arguments)]");
    t.open(format!(
        "fn handle_{}<S: {trait_name}>(server: &mut S, caller: &S::Caller, oidl_header: rt::Header, oidl_body: &[u8], handles: &[rt::RecvHandle], oidl_minor: u16, reply: &mut [u8], reply_handles: &mut [u32]) -> rt::Dispatched {{",
        method.name
    ));
    t.line("let _ = (&oidl_minor, &reply, &reply_handles, &oidl_header);");
    if let Some(requirement) = &method.requires {
        t.open(format!(
            "if !server.holds(caller, Capability::{}) {{",
            pascal(&requirement.capability.ident())
        ));
        if method.oneway {
            t.line("return rt::Dispatched::NoReply { taken: false };");
        } else {
            t.line(format!(
                "return rt::refuse(reply, oidl_header.ordinal, oidl_header.txid, {status}::AccessDenied.raw());"
            ));
        }
        t.shut("}");
    }
    t.line("let mut oidl_list = rt::HandleList::new(handles);");
    t.open(format!(
        "let Ok(oidl_request) = {base_name}Request::decode(oidl_body, &mut oidl_list, oidl_minor) else {{"
    ));
    if method.oneway {
        t.line("return rt::Dispatched::NoReply { taken: false };");
    } else {
        t.line(format!(
            "return rt::refuse(reply, oidl_header.ordinal, oidl_header.txid, {status}::InvalidArgs.raw());"
        ));
    }
    t.shut("};");
    if method.oneway {
        t.line(format!("server.{}(caller, oidl_request);", method.name));
        t.line("rt::Dispatched::NoReply { taken: true }");
    } else {
        t.open(format!(
            "match server.{}(caller, oidl_request) {{",
            method.name
        ));
        t.open("Ok(oidl_args) => {");
        // The service ran and took the received handles: a reply that cannot be encoded closes
        // the connection, but those handles are the service's now (§7.8).
        t.open(
            "let Some((oidl_head, oidl_tail)) = reply.split_at_mut_checked(rt::HEADER_SIZE) else {",
        );
        t.line("return rt::Dispatched::Close { taken: true };");
        t.shut("};");
        t.line("let mut oidl_sink = rt::HandleSink::new(reply_handles);");
        t.open(
            "let Ok(oidl_size) = oidl_args.encode(oidl_tail, &mut oidl_sink, oidl_minor) else {",
        );
        t.line("return rt::Dispatched::Close { taken: true };");
        t.shut("};");
        t.line("let oidl_total = rt::HEADER_SIZE.saturating_add(oidl_size);");
        t.open("if rt::write_header(oidl_head, rt::KIND_RESPONSE, oidl_header.ordinal, oidl_header.txid, oidl_total).is_err() {");
        t.line("return rt::Dispatched::Close { taken: true };");
        t.shut("}");
        t.line(
            "rt::Dispatched::Reply { bytes: oidl_total, handles: oidl_sink.used(), taken: true }",
        );
        t.shut("}");
        t.line("Err(oidl_error) => rt::method_error(reply, oidl_header.ordinal, oidl_header.txid, oidl_error.error().raw()),");
        t.shut("}");
    }
    t.shut("}");
    t.blank();
}

fn gen_channel_client(g: &Gen<'_>, interface: &Interface) -> String {
    let mut t = Text::default();
    let status = g.status_path(3);
    let name = format!("{}Client", pascal(&interface.name));
    t.line("//! Safe client of the interface (§11).");
    t.line(SAFE_ATTRS.trim_end());
    t.blank();
    t.line(format!("use {} as rt;", Gen::rt(3)));
    t.line("#[allow(unused_imports)]");
    t.line("use super::super::types::*;");
    t.line("use super::server::*;");
    t.blank();
    t.line("/// The refusal statuses a client may see (§7.8).");
    t.open("fn classify<E: rt::MethodError>(oidl_status: i64) -> rt::CallError<E> {");
    t.open("match E::from_status(oidl_status) {");
    t.line("Some(error) => rt::CallError::Method(error),");
    t.line(format!(
        "None if oidl_status == {status}::InvalidArgs.raw() || oidl_status == {status}::NotSupported.raw() || oidl_status == {status}::AccessDenied.raw() => rt::CallError::Refused(oidl_status),"
    ));
    t.line("None => rt::CallError::Undeclared(oidl_status),");
    t.shut("}");
    t.shut("}");
    t.blank();
    t.line("/// A connection to the interface: a transport and the negotiated minor.");
    t.line("#[derive(Debug)]");
    t.open(format!("pub struct {name}<T> {{"));
    t.line("transport: T,");
    t.line("minor: u16,");
    t.line("txid: u32,");
    t.shut("}");
    t.blank();
    t.open(format!("impl<T: rt::Transport> {name}<T> {{"));
    t.line("/// Runs the hello (§7.7).");
    t.open("pub fn connect(mut transport: T, scratch: &mut rt::Scratch<'_>) -> Result<Self, rt::CallError<core::convert::Infallible>> {");
    t.line("let oidl_hello = rt::Hello { interface_id: INTERFACE_ID, major: VERSION.0, minor: VERSION.1 };");
    t.line("let oidl_total = rt::write_hello(scratch.bytes, rt::KIND_REQUEST, 1, oidl_hello).map_err(rt::CallError::Protocol)?;");
    t.line("let (oidl_n, oidl_h) = transport.call(scratch.bytes, oidl_total, &[], scratch.received).map_err(rt::CallError::Transport)?;");
    t.line("let oidl_received = scratch.received.get(..oidl_h).ok_or(rt::CallError::Protocol(rt::WireError::HandleCount))?;");
    t.line("let oidl_message = scratch.bytes.get(..oidl_n).ok_or(rt::CallError::Protocol(rt::WireError::Size))?;");
    t.open(
        "match rt::read_hello_reply(oidl_message, oidl_h, INTERFACE_ID, VERSION.0, VERSION.1) {",
    );
    t.line("Ok(minor) => Ok(Self { transport, minor, txid: 1 }),");
    t.open("Err(oidl_error) => {");
    t.line("transport.discard(oidl_received);");
    t.line("Err(oidl_error)");
    t.shut("}");
    t.shut("}");
    t.shut("}");
    t.blank();
    t.open("fn next_txid(&mut self) -> u32 {");
    t.line("self.txid = self.txid.wrapping_add(1);");
    t.open("if self.txid == 0 {");
    t.line("self.txid = 1;");
    t.shut("}");
    t.line("self.txid");
    t.shut("}");
    t.blank();
    t.line("/// The negotiated minor.");
    t.open("pub const fn minor(&self) -> u16 {");
    t.line("self.minor");
    t.shut("}");
    t.blank();
    t.line("/// The transport this client uses.");
    t.open("pub const fn transport(&self) -> &T {");
    t.line("&self.transport");
    t.shut("}");
    t.blank();
    for method in &interface.methods {
        gen_channel_client_method(g, &mut t, method);
    }
    t.shut("}");
    t.blank();
    for method in &interface.methods {
        gen_channel_reply_decoder(&mut t, method);
    }
    t.finish()
}

/// The checks on a reply: anything that fails leaves the caller to close the handles received.
fn gen_channel_reply_decoder(t: &mut Text, method: &Method) {
    if method.oneway {
        return;
    }
    let base_name = pascal(&method.name);
    let response_lifetime = if has_borrow(&method.returns) {
        "<'b>"
    } else {
        ""
    };
    t.open(format!(
        "fn decode_{}_reply<'b>(oidl_message: &'b [u8], oidl_received: &'b [rt::RecvHandle], oidl_txid: u32, oidl_minor: u16) -> Result<{base_name}Response{response_lifetime}, rt::CallError<{base_name}Error>> {{",
        method.name
    ));
    t.line("let oidl_header = rt::read_header(oidl_message).map_err(rt::CallError::Protocol)?;");
    t.open(format!(
        "if oidl_header.ordinal != ordinal::{} || oidl_header.txid != oidl_txid {{",
        shouty(&method.name)
    ));
    t.line("return Err(rt::CallError::Protocol(rt::WireError::Ordinal));");
    t.shut("}");
    t.line("let oidl_body: &'b [u8] = oidl_message.get(rt::HEADER_SIZE..).unwrap_or(&[]);");
    t.open("if oidl_header.kind == rt::KIND_ERROR {");
    // §7.6: an error reply has no fields but the status, and carries no handles.
    t.open("if !oidl_received.is_empty() {");
    t.line("return Err(rt::CallError::Protocol(rt::WireError::HandleCount));");
    t.shut("}");
    t.line("let oidl_status = rt::read_error_status(oidl_body).map_err(rt::CallError::Protocol)?;");
    t.line("return Err(classify(oidl_status));");
    t.shut("}");
    t.open("if oidl_header.kind != rt::KIND_RESPONSE {");
    t.line("return Err(rt::CallError::Protocol(rt::WireError::Direction));");
    t.shut("}");
    t.line("let mut oidl_list = rt::HandleList::new(oidl_received);");
    t.line(format!(
        "{base_name}Response::decode(oidl_body, &mut oidl_list, oidl_minor).map_err(rt::CallError::Protocol)"
    ));
    t.shut("}");
    t.blank();
}

fn gen_channel_client_method(g: &Gen<'_>, t: &mut Text, method: &Method) {
    let base_name = pascal(&method.name);
    let args_borrow = if has_borrow(&method.params) {
        "<'_>"
    } else {
        ""
    };
    t.doc(&method.doc);
    if method.oneway {
        t.open(format!(
            "pub fn {}(&mut self, scratch: &mut rt::Scratch<'_>, args: {base_name}RequestArgs{args_borrow}) -> Result<(), rt::CallError<core::convert::Infallible>> {{",
            method.name
        ));
    } else {
        let response_lifetime = if has_borrow(&method.returns) {
            "<'b>"
        } else {
            ""
        };
        t.open(format!(
            "pub fn {}<'b>(&mut self, scratch: &'b mut rt::Scratch<'_>, args: {base_name}RequestArgs{args_borrow}) -> Result<{base_name}Response{response_lifetime}, rt::CallError<{base_name}Error>> {{",
            method.name
        ));
    }
    if method.since.minor > 0 {
        t.open(format!("if self.minor < {} {{", method.since.minor));
        t.line(format!(
            "return Err(rt::CallError::Refused({}::NotSupported.raw()));",
            g.status_path(3)
        ));
        t.shut("}");
    }
    if method.oneway {
        t.line("let oidl_txid = 0;");
    } else {
        t.line("let oidl_txid = self.next_txid();");
    }
    t.line("let (oidl_head, oidl_tail) = scratch.bytes.split_at_mut_checked(rt::HEADER_SIZE).ok_or(rt::CallError::Protocol(rt::WireError::Size))?;");
    t.line("let mut oidl_sink = rt::HandleSink::new(scratch.handles);");
    t.line("let oidl_size = args.encode(oidl_tail, &mut oidl_sink, self.minor).map_err(rt::CallError::Protocol)?;");
    t.line("let oidl_total = rt::HEADER_SIZE.saturating_add(oidl_size);");
    t.line(format!(
        "rt::write_header(oidl_head, rt::KIND_REQUEST, ordinal::{}, oidl_txid, oidl_total).map_err(rt::CallError::Protocol)?;",
        shouty(&method.name)
    ));
    t.line("let oidl_handle_count = oidl_sink.used();");
    t.line("let oidl_sent = scratch.handles.get(..oidl_handle_count).unwrap_or(&[]);");
    if method.oneway {
        t.line("let oidl_message = scratch.bytes.get(..oidl_total).ok_or(rt::CallError::Protocol(rt::WireError::Size))?;");
        t.line("self.transport.send(oidl_message, oidl_sent).map_err(rt::CallError::Transport)");
        t.shut("}");
        t.blank();
        return;
    }
    t.line("let (oidl_n, oidl_h) = self.transport.call(scratch.bytes, oidl_total, oidl_sent, scratch.received).map_err(rt::CallError::Transport)?;");
    t.line("let oidl_message: &'b [u8] = scratch.bytes.get(..oidl_n).ok_or(rt::CallError::Protocol(rt::WireError::Size))?;");
    t.line("let oidl_received: &'b [rt::RecvHandle] = scratch.received.get(..oidl_h).ok_or(rt::CallError::Protocol(rt::WireError::HandleCount))?;");
    t.line(format!(
        "let oidl_result = decode_{}_reply(oidl_message, oidl_received, oidl_txid, self.minor);",
        method.name
    ));
    t.open("if oidl_result.is_err() {");
    t.line("self.transport.discard(oidl_received);");
    t.shut("}");
    t.line("oidl_result");
    t.shut("}");
    t.blank();
}

// --- Files ---------------------------------------------------------------------------------

fn gen_library(comp: &Compilation, lib: &Library, side: Side, files: &mut Vec<Generated>) {
    let m = module(&lib.name);
    let g = Gen { comp, lib };
    let top = side.top();
    let mut root = Text::default();
    root.line(format!(
        "//! `{}`, generated from its definition.",
        lib.name
    ));
    root.blank();
    root.line("pub mod types;");
    root.line("pub use types::*;");
    for interface in &lib.interfaces {
        root.line(format!("pub mod {};", interface.name));
    }
    files.push(Generated {
        path: format!("{top}{m}/mod.rs"),
        text: format!("{HEADER}{}", root.finish()),
    });
    files.push(Generated {
        path: format!("{top}{m}/types.rs"),
        text: format!("{HEADER}{}", gen_types(&g)),
    });
    for interface in &lib.interfaces {
        let dir = format!("{top}{m}/{}", interface.name);
        let mut module_text = Text::default();
        module_text.line(format!("//! The `{}` interface.", interface.name));
        module_text.blank();
        module_text.line("pub mod server;");
        let server = match lib.transport {
            Transport::Syscall => gen_sys_server(&g, interface),
            Transport::Channel => gen_channel_server(&g, interface),
        };
        files.push(Generated {
            path: format!("{dir}/server.rs"),
            text: format!("{HEADER}{server}"),
        });
        // A library crate is made only for a channel library, whose client needs no shim.
        if side != Side::Server {
            module_text.line("pub mod client;");
            match lib.transport {
                Transport::Syscall => {
                    module_text.line("mod abi;");
                    module_text.line("#[cfg(target_arch = \"x86_64\")]");
                    module_text.line("pub mod core_stubs;");
                    files.push(Generated {
                        path: format!("{dir}/client.rs"),
                        text: format!("{HEADER}{}", gen_sys_client(&g, interface)),
                    });
                    files.push(Generated {
                        path: format!("{dir}/abi.rs"),
                        text: format!("{HEADER}{}", gen_sys_abi(&g, interface)),
                    });
                    files.push(Generated {
                        path: format!("{dir}/core_stubs.rs"),
                        text: format!("{HEADER}{}", gen_sys_core_stubs(&g, interface)),
                    });
                }
                Transport::Channel => {
                    files.push(Generated {
                        path: format!("{dir}/client.rs"),
                        text: format!("{HEADER}{}", gen_channel_client(&g, interface)),
                    });
                }
            }
        }
        files.push(Generated {
            path: format!("{dir}/mod.rs"),
            text: format!("{HEADER}{}", module_text.finish()),
        });
    }
}

// --- The corpus runner ---------------------------------------------------------------------

fn gen_corpus_check(comp: &Compilation) -> String {
    let mut t = Text::default();
    t.line("//! Runs the hostile corpus against the generated code (§14).");
    t.blank();
    t.line("use oidl_generated::oidl_rt as rt;");
    t.blank();
    for lib in &comp.libraries {
        if lib.transport != Transport::Syscall {
            continue;
        }
        let g = Gen { comp, lib };
        let m = module(&lib.name);
        for interface in &lib.interfaces {
            let path = format!("oidl_generated::{m}::{}::server", interface.name);
            let name = format!("Null{}{}", pascal(&m), pascal(&interface.name));
            t.line("#[allow(non_camel_case_types)]");
            t.line(format!("struct {name} {{ holds: bool }}"));
            t.open(format!("impl {path}::Calls for {name} {{"));
            if !lib.capabilities.is_empty() {
                t.line(format!(
                    "fn holds(&self, _capability: oidl_generated::{m}::Capability) -> bool {{ self.holds }}"
                ));
            }
            for method in &interface.methods {
                if method.reserved {
                    continue;
                }
                let mut args = vec!["&self".to_string()];
                for param in &method.params {
                    args.push(format!(
                        "_{}: {}",
                        param.name,
                        corpus_path(&sys_server_ty(&g, param, false), &m)
                    ));
                }
                for result in &method.returns {
                    args.push(format!(
                        "_{}: {}",
                        result.name,
                        corpus_path(&sys_server_ty(&g, result, true), &m)
                    ));
                }
                if method.never {
                    t.line(format!("fn {}({}) {{}}", method.name, args.join(", ")));
                } else {
                    t.line(format!(
                        "fn {}({}) -> Result<(), {path}::{}Error> {{ Ok(()) }}",
                        method.name,
                        args.join(", "),
                        pascal(&method.name)
                    ));
                }
            }
            t.shut("}");
            t.blank();
        }
    }
    t.open("fn check_syscall(library: &str, interface: &str, number: u64, holds: bool, args: [u64; 6]) -> i64 {");
    t.open("match (library, interface) {");
    for lib in &comp.libraries {
        if lib.transport != Transport::Syscall {
            continue;
        }
        let m = module(&lib.name);
        for interface in &lib.interfaces {
            let path = format!("oidl_generated::{m}::{}::server", interface.name);
            let name = format!("Null{}{}", pascal(&m), pascal(&interface.name));
            t.open(format!("(\"{}\", \"{}\") => {{", lib.name, interface.name));
            t.line(format!(
                "match {path}::dispatch(&{name} {{ holds }}, number, args) {{"
            ));
            t.line(format!("    {path}::Outcome::Status(s) => s,"));
            t.line(format!("    {path}::Outcome::ThreadExit => 0,"));
            t.line("}");
            t.shut("}");
        }
    }
    t.line("_ => panic!(\"unknown interface {library} {interface}\"),");
    t.shut("}");
    t.shut("}");
    t.blank();
    t.line("#[allow(unused_variables)]");
    t.open("fn check_message(library: &str, interface: &str, method: &str, request: bool, minor: u16, message: &[u8], handles: &[rt::RecvHandle]) -> Result<(), rt::WireError> {");
    t.line("let header = rt::read_header(message)?;");
    t.line("let expected = if request { rt::KIND_REQUEST } else { rt::KIND_RESPONSE };");
    t.open("if header.kind != expected {");
    t.line("return Err(rt::WireError::Direction);");
    t.shut("}");
    t.line("let body = message.get(rt::HEADER_SIZE..).unwrap_or(&[]);");
    t.line("#[allow(unused_mut)]");
    t.line("let mut list = rt::HandleList::new(handles);");
    t.open("match (library, interface, method, request) {");
    for lib in &comp.libraries {
        if lib.transport != Transport::Channel {
            continue;
        }
        let m = module(&lib.name);
        for interface in &lib.interfaces {
            let path = format!("oidl_generated::{m}::{}::server", interface.name);
            for method in &interface.methods {
                let base_name = pascal(&method.name);
                let txid_ok = if method.oneway {
                    "header.txid == 0"
                } else {
                    "header.txid != 0"
                };
                t.open(format!(
                    "(\"{}\", \"{}\", \"{}\", true) => {{",
                    lib.name, interface.name, method.name
                ));
                t.line(format!(
                    "if !({txid_ok}) {{ return Err(rt::WireError::Txid); }}"
                ));
                t.line(format!(
                    "if header.ordinal != {} {{ return Err(rt::WireError::Ordinal); }}",
                    method.ordinal
                ));
                t.line(format!(
                    "{path}::{base_name}Request::decode(body, &mut list, minor).map(|_| ())"
                ));
                t.shut("}");
                if !method.oneway {
                    t.open(format!(
                        "(\"{}\", \"{}\", \"{}\", false) => {{",
                        lib.name, interface.name, method.name
                    ));
                    t.line("if header.txid == 0 { return Err(rt::WireError::Txid); }");
                    t.line(format!(
                        "if header.ordinal != {} {{ return Err(rt::WireError::Ordinal); }}",
                        method.ordinal
                    ));
                    t.line(format!(
                        "{path}::{base_name}Response::decode(body, &mut list, minor).map(|_| ())"
                    ));
                    t.shut("}");
                }
            }
        }
    }
    t.line("_ => panic!(\"unknown method {library} {interface} {method}\"),");
    t.shut("}");
    t.shut("}");
    t.blank();
    t.line("/// A status as the corpus names it.");
    t.open("fn status_text(raw: i64) -> String {");
    match status_enum(comp) {
        Some(status) => t.line(format!(
            "oidl_generated::{}::status_name(raw).to_ascii_lowercase()",
            module(&status.library)
        )),
        None => t.line("format!(\"{raw}\")"),
    }
    t.shut("}");
    t.blank();
    t.line(include_str!("corpus_check_main.rs.in"));
    t.finish()
}

/// Rewrites a server-side type written relative to an interface module into one that resolves
/// from the corpus runner's crate root.
fn corpus_path(ty: &str, module_name: &str) -> String {
    let rewritten = ty
        .replace("rt::", "oidl_generated::oidl_rt::")
        .replace("super::super::super::", "oidl_generated::");
    // A bare local type name.
    let mut out = String::new();
    let mut token = String::new();
    let flush = |token: &mut String, out: &mut String| {
        let first_upper = token.chars().next().is_some_and(|c| c.is_ascii_uppercase());
        if first_upper
            && !token.contains("::")
            && !out.ends_with("::")
            && !matches!(token.as_str(), "Option")
        {
            out.push_str(&format!("oidl_generated::{module_name}::{token}"));
        } else {
            out.push_str(token);
        }
        token.clear();
    };
    for c in rewritten.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            token.push(c);
        } else {
            flush(&mut token, &mut out);
            out.push(c);
        }
    }
    flush(&mut token, &mut out);
    out
}

/// Every Rust file.
pub fn generate(comp: &Compilation) -> Vec<Generated> {
    let all: Vec<&Library> = comp.libraries.iter().collect();
    let mut files = gen_crate(comp, Side::Everything, &all, None);
    files.push(Generated {
        path: "rust/bin/corpus_check.rs".to_string(),
        text: format!("{HEADER}{}", gen_corpus_check(comp)),
    });
    files
}

/// The server side alone (`docs/spec/OIDL.md` §11), as a crate of its own: the runtime, the types
/// and the server modules, with no client, no C entry points and so no `unsafe` at all. The
/// compiler holds it to that: its root is `forbid(unsafe_code)`.
pub fn generate_server(comp: &Compilation) -> Vec<Generated> {
    let all: Vec<&Library> = comp.libraries.iter().collect();
    gen_crate(comp, Side::Server, &all, None)
}

/// One `channel` library's bindings (`docs/spec/OIDL.md` §11), as a crate of its own: the
/// runtime, the library's types, and each of its interfaces' server and client; of the libraries
/// it uses, directly or not, only their types. A channel client needs no shim, so there is no
/// `unsafe` at all, and the root is `forbid(unsafe_code)`. Refused for a library that is not
/// among the definitions, and for a `syscall` library, whose client is the shims.
pub fn generate_library(comp: &Compilation, name: &str) -> Result<Vec<Generated>, String> {
    let Some(selected) = comp.libraries.iter().find(|lib| lib.name == name) else {
        return Err(format!("{name} is not among the definitions given"));
    };
    if selected.transport != Transport::Channel {
        return Err(format!(
            "{name} is a syscall library: its client is the C-ABI shims, which only the full output writes"
        ));
    }
    // What it uses, directly or not. `libraries` lists each after every library it uses, so one
    // pass from the end finds them all.
    let mut wanted = vec![name];
    for lib in comp.libraries.iter().rev() {
        if wanted.contains(&lib.name.as_str()) {
            for used in &lib.uses {
                if !wanted.contains(&used.as_str()) {
                    wanted.push(used.as_str());
                }
            }
        }
    }
    let included: Vec<&Library> = comp
        .libraries
        .iter()
        .filter(|lib| wanted.contains(&lib.name.as_str()))
        .collect();
    Ok(gen_crate(comp, Side::Library, &included, Some(name)))
}

/// A crate of `libraries`: in full where `selected` is `None` or names it, otherwise only its
/// types.
fn gen_crate(
    comp: &Compilation,
    side: Side,
    libraries: &[&Library],
    selected: Option<&str>,
) -> Vec<Generated> {
    let top = side.top();
    let mut files = vec![Generated {
        path: format!("{top}oidl_rt.rs"),
        text: format!("{HEADER}{}", include_str!("oidl_rt.rs.in")),
    }];
    let mut root = Text::default();
    root.line("//! Generated from the OIDL definitions. `docs/spec/OIDL.md`.");
    root.line("//!");
    root.line("#![no_std]");
    root.line(match side {
        Side::Everything => "#![deny(unsafe_op_in_unsafe_fn)]",
        Side::Server | Side::Library => "#![forbid(unsafe_code)]",
    });
    root.blank();
    // What the tool wrote is what is committed and compared, so rustfmt leaves it alone.
    root.line("#[rustfmt::skip]");
    root.line("pub mod oidl_rt;");
    for lib in libraries {
        root.line("#[rustfmt::skip]");
        root.line(format!("pub mod {};", module(&lib.name)));
    }
    files.push(Generated {
        path: format!("{top}lib.rs"),
        text: format!("{HEADER}{}", root.finish()),
    });
    for lib in libraries {
        if selected.is_none_or(|name| name == lib.name) {
            gen_library(comp, lib, side, &mut files);
        } else {
            gen_types_only(comp, lib, side, &mut files);
        }
    }
    files
}

/// A used library in a library crate: its types, and none of its interfaces.
fn gen_types_only(comp: &Compilation, lib: &Library, side: Side, files: &mut Vec<Generated>) {
    let m = module(&lib.name);
    let g = Gen { comp, lib };
    let top = side.top();
    let mut root = Text::default();
    root.line(format!(
        "//! `{}`'s types, generated from its definition. Its interfaces are not part of this crate.",
        lib.name
    ));
    root.blank();
    root.line("pub mod types;");
    root.line("pub use types::*;");
    files.push(Generated {
        path: format!("{top}{m}/mod.rs"),
        text: format!("{HEADER}{}", root.finish()),
    });
    files.push(Generated {
        path: format!("{top}{m}/types.rs"),
        text: format!("{HEADER}{}", gen_types(&g)),
    });
}
