const HEADER: &str = "// @generated by oidl. Do not edit. docs/spec/OIDL.md\n";

const SAFE_ATTRS: &str = "#![forbid(unsafe_code)]\n#![deny(\n    clippy::panic,\n    clippy::unwrap_used,\n    clippy::expect_used,\n    clippy::indexing_slicing,\n    clippy::arithmetic_side_effects,\n    clippy::cast_possible_truncation\n)]\n";

/// The Rust name of an enum: the `status` role is `Error` (and `OK`), like `origin-abi`.
fn enum_name(e: &Enum) -> String {
    if e.name == "status" {
        "Error".to_string()
    } else {
        pascal(&e.name)
    }
}

fn status_enum(comp: &Compilation) -> Option<&Enum> {
    comp.status.as_deref()
}

/// Which part of the output to write.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Side {
    /// Everything, under `rust/`.
    Everything,
    /// The server side alone, at the top of the output directory.
    Server,
    /// One channel library's server and client, at the top of the output directory, with only
    /// the types of the libraries it uses.
    Library,
}

impl Side {
    /// The directory the crate is written under, with its slash.
    const fn top(self) -> &'static str {
        match self {
            Self::Everything => "rust/",
            Self::Server | Self::Library => "",
        }
    }
}

struct Gen<'a> {
    comp: &'a Compilation,
    lib: &'a Library,
}

impl Gen<'_> {
    fn rt(depth: usize) -> String {
        format!("{}oidl_rt", "super::".repeat(depth))
    }

    /// A path from a module `depth` levels below the crate root to an item of `library`.
    fn path(&self, depth: usize, library: &str, item: &str) -> String {
        if library == self.lib.name {
            item.to_string()
        } else {
            format!("{}{}::{item}", "super::".repeat(depth), module(library))
        }
    }

    fn fixed(&self, depth: usize, ty: &Type) -> String {
        match ty {
            Type::Bool => "bool".to_string(),
            Type::Int(int) => int.rust().to_string(),
            Type::Enum(e) => self.path(depth, &e.library, &enum_name(e)),
            Type::Bits(b) => self.path(depth, &b.library, &pascal(&b.name)),
            Type::Struct(s) => self.path(depth, &s.library, &pascal(&s.name)),
            Type::Array(elem, count) => format!("[{}; {count}]", self.fixed(depth, elem)),
            Type::Vector(..) | Type::String(_) | Type::Handle(_) => "()".to_string(),
        }
    }

    fn status_path(&self, depth: usize) -> String {
        match status_enum(self.comp) {
            Some(e) => self.path(depth, &e.library, "Error"),
            None => "Error".to_string(),
        }
    }

    fn c_prefix(&self) -> String {
        module(&self.lib.name)
    }

    /// What to pass as `minor` when reading a value of type `ty` from a context in library
    /// `current` at minor `local`. An enum's or bits' members are versioned by the library that
    /// declares them, and only this library's minor is negotiated (§9), so a type from another
    /// library is read with every member known.
    fn minor_arg(ty: &Type, current: &str, local: &str) -> String {
        match type_library(ty) {
            Some(library) if library != current => "u16::MAX".to_string(),
            _ => local.to_string(),
        }
    }
}

/// The library that declares `ty`, if it is an item of one.
fn type_library(ty: &Type) -> Option<&str> {
    match ty {
        Type::Enum(e) => Some(&e.library),
        Type::Bits(b) => Some(&b.library),
        Type::Struct(s) => Some(&s.library),
        Type::Array(elem, _) | Type::Vector(elem, _) => type_library(elem),
        _ => None,
    }
}

fn base(version: Version) -> Version {
    Version {
        major: version.major,
        minor: 0,
    }
}

fn has_borrow(params: &[Param]) -> bool {
    params
        .iter()
        .any(|p| matches!(p.ty, Type::Vector(..) | Type::String(_)))
}

/// Distinct minors of `params`, ascending.
fn groups(params: &[Param]) -> Vec<u16> {
    let mut minors: Vec<u16> = params.iter().map(|p| p.since.minor).collect();
    minors.sort_unstable();
    minors.dedup();
    minors
}

/// The doc comment for a struct field, a parameter or a member.
fn field_doc(t: &mut Text, doc: &[String]) {
    t.doc(doc);
}

