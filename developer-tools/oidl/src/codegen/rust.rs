//! The Rust generator (`docs/spec/OIDL.md` §11). Generated code is `no_std`, allocates nothing,
//! obeys the project's no-panic lints and holds no `unsafe` outside `abi.rs` and `core_stubs.rs`
//! (ADR-0011 S7).

