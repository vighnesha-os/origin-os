fn gen_const(g: &Gen<'_>, t: &mut Text, c: &crate::model::Const) {
    t.doc(&c.doc);
    match &c.kind {
        crate::model::ConstKind::Int(int) => {
            t.line(format!(
                "pub const {}: {} = {};",
                shouty(&c.name),
                int.rust(),
                c.value
            ));
        }
        crate::model::ConstKind::Bits(bits) => {
            let path = g.path(2, &bits.library, &pascal(&bits.name));
            t.line(format!(
                "pub const {}: {path} = match {path}::from_bits({:#x}) {{ Some(value) => value, None => {path}::NONE }};",
                shouty(&c.name),
                c.value
            ));
        }
    }
    t.blank();
}

fn gen_enum(t: &mut Text, e: &Enum, is_status: bool) {
    let name = enum_name(e);
    let repr = e.repr.rust();
    if is_status {
        t.line("/// The success status.");
        t.line("pub const OK: i64 = 0;");
        t.blank();
    }
    let members: Vec<_> = e
        .members
        .iter()
        .filter(|m| !(is_status && m.name == "ok"))
        .collect();
    t.doc(&e.doc);
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.line(format!("#[repr({repr})]"));
    t.line("#[non_exhaustive]");
    t.open(format!("pub enum {name} {{"));
    for member in &members {
        field_doc(t, &member.doc);
        t.line(format!("{} = {},", pascal(&member.name), member.value));
    }
    t.shut("}");
    t.blank();
    t.open(format!("impl {name} {{"));
    t.line("/// Every member, in declaration order.");
    let list: Vec<String> = members
        .iter()
        .map(|m| format!("Self::{}", pascal(&m.name)))
        .collect();
    t.line(format!(
        "pub const ALL: [Self; {}] = [{}];",
        list.len(),
        list.join(", ")
    ));
    t.blank();
    t.line("/// The value on the wire or in a register.");
    t.open(format!("pub const fn raw(self) -> {repr} {{"));
    t.line(format!("self as {repr}"));
    t.shut("}");
    t.blank();
    t.line("/// The member with this value, if there is one.");
    t.open(format!("pub fn from_raw(raw: {repr}) -> Option<Self> {{"));
    t.line("Self::ALL.iter().copied().find(|e| e.raw() == raw)");
    t.shut("}");
    t.blank();
    t.line("/// This value's name in the C ABI.");
    t.open("pub const fn name(self) -> &'static str {");
    t.open("match self {");
    for member in &members {
        t.line(format!(
            "Self::{} => \"{}\",",
            pascal(&member.name),
            shouty(&member.name)
        ));
    }
    t.shut("}");
    t.shut("}");
    t.blank();
    if !is_status {
        t.line("/// The first minor it is valid at.");
        t.open("const fn since_minor(self) -> u16 {");
        t.open("match self {");
        for member in &members {
            t.line(format!(
                "Self::{} => {},",
                pascal(&member.name),
                member.since.minor
            ));
        }
        t.shut("}");
        t.shut("}");
    }
    t.shut("}");
    t.blank();
    if is_status {
        t.line("/// The name of a raw status: `OK`, an [`Error`]'s name, or `UNKNOWN` for anything else.");
        t.open("pub fn status_name(raw: i64) -> &'static str {");
        t.open("if raw == OK {");
        t.line("\"OK\"");
        t.reopen("} else {");
        t.open("match Error::from_raw(raw) {");
        t.line("Some(e) => e.name(),");
        t.line("None => \"UNKNOWN\",");
        t.shut("}");
        t.shut("}");
        t.shut("}");
        t.blank();
        return;
    }
    t.open(format!("impl rt::Fixed for {name} {{"));
    t.line(format!("const SIZE: usize = {};", e.repr.size()));
    if let Some(first) = members.first() {
        t.line(format!(
            "const FILLER: Self = Self::{};",
            pascal(&first.name)
        ));
    }
    t.open("fn read(bytes: &[u8], minor: u16) -> Result<Self, rt::WireError> {");
    t.line(format!(
        "let raw = <{repr} as rt::Fixed>::read(bytes, minor)?;"
    ));
    t.line("let value = Self::from_raw(raw).ok_or(rt::WireError::Enum)?;");
    t.open("if minor < value.since_minor() {");
    t.line("return Err(rt::WireError::Enum);");
    t.shut("}");
    t.line("Ok(value)");
    t.shut("}");
    t.open("fn write(self, out: &mut [u8]) -> Result<(), rt::WireError> {");
    t.line("rt::Fixed::write(self.raw(), out)");
    t.shut("}");
    t.shut("}");
    t.blank();
}

fn gen_bits(t: &mut Text, b: &Bits) {
    let name = pascal(&b.name);
    let repr = b.repr.rust();
    t.doc(&b.doc);
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.line("#[repr(transparent)]");
    t.line(format!("pub struct {name}({repr});"));
    t.blank();
    t.open(format!("impl {name} {{"));
    let mut all: u64 = 0;
    for member in &b.members {
        let mask = 1u64 << member.value;
        all |= mask;
        field_doc(t, &member.doc);
        t.line(format!(
            "pub const {}: Self = Self({mask:#x});",
            shouty(&member.name)
        ));
    }
    t.line("/// No bits.");
    t.line("pub const NONE: Self = Self(0);");
    t.line("/// Every bit defined in this version.");
    t.line(format!("pub const ALL: Self = Self({all:#x});"));
    t.blank();
    t.line("/// The raw value.");
    t.open(format!("pub const fn bits(self) -> {repr} {{"));
    t.line("self.0");
    t.shut("}");
    t.blank();
    t.line("/// The value with these bits, or `None` if a bit is undefined.");
    t.open(format!(
        "pub const fn from_bits(raw: {repr}) -> Option<Self> {{"
    ));
    t.open("if raw & !Self::ALL.0 == 0 {");
    t.line("Some(Self(raw))");
    t.shut("} else {");
    t.line("None");
    t.shut("}");
    t.shut("}");
    t.blank();
    t.line("/// Whether every bit of `other` is set.");
    t.open("pub const fn contains(self, other: Self) -> bool {");
    t.line("self.0 & other.0 == other.0");
    t.shut("}");
    t.blank();
    t.line("/// The bits of both.");
    t.open("pub const fn union(self, other: Self) -> Self {");
    t.line("Self(self.0 | other.0)");
    t.shut("}");
    t.blank();
    t.line("/// The bits known at `minor`.");
    t.open(format!("pub const fn known(minor: u16) -> {repr} {{"));
    let gated: Vec<_> = b.members.iter().filter(|m| m.since.minor > 0).collect();
    if gated.is_empty() {
        t.line("let _ = minor;");
        t.line("Self::ALL.0");
    } else {
        t.line("let mut mask = Self::ALL.0;");
        for member in gated {
            let bit = 1u64 << member.value;
            t.line(format!(
                "if minor < {} {{ mask &= !{bit:#x}; }}",
                member.since.minor
            ));
        }
        t.line("mask");
    }
    t.shut("}");
    t.shut("}");
    t.blank();
    t.open(format!("impl rt::Fixed for {name} {{"));
    t.line(format!("const SIZE: usize = {};", b.repr.size()));
    t.line("const FILLER: Self = Self(0);");
    t.open("fn read(bytes: &[u8], minor: u16) -> Result<Self, rt::WireError> {");
    t.line(format!(
        "let raw = <{repr} as rt::Fixed>::read(bytes, minor)?;"
    ));
    t.open("if raw & !Self::known(minor) != 0 {");
    t.line("return Err(rt::WireError::Bits);");
    t.shut("}");
    t.line("Ok(Self(raw))");
    t.shut("}");
    t.open("fn write(self, out: &mut [u8]) -> Result<(), rt::WireError> {");
    t.line("rt::Fixed::write(self.0, out)");
    t.shut("}");
    t.shut("}");
    t.blank();
}

enum Step<'s> {
    Field(&'s crate::model::Field),
    Pad(u32, u32),
}

fn steps_of(s: &Struct) -> Vec<(u32, Step<'_>)> {
    let mut steps: Vec<(u32, Step<'_>)> = s
        .fields
        .iter()
        .map(|f| (f.offset, Step::Field(f)))
        .chain(
            s.padding
                .iter()
                .map(|(at, len)| (*at, Step::Pad(*at, *len))),
        )
        .collect();
    steps.sort_by_key(|(at, _)| *at);
    steps
}

fn gen_fixed_struct(g: &Gen<'_>, t: &mut Text, s: &Struct) {
    let name = pascal(&s.name);
    t.doc(&s.doc);
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.open(format!("pub struct {name} {{"));
    for field in &s.fields {
        field_doc(t, &field.doc);
        t.line(format!("pub {}: {},", field.name, g.fixed(2, &field.ty)));
    }
    t.shut("}");
    t.blank();
    t.open(format!("impl {name} {{"));
    for field in &s.fields {
        t.line(format!("/// Byte offset of `{}`.", field.name));
        t.line(format!(
            "pub const {}_AT: usize = {};",
            shouty(&field.name),
            field.offset
        ));
    }
    t.shut("}");
    t.blank();
    t.open(format!("impl rt::Fixed for {name} {{"));
    t.line(format!("const SIZE: usize = {};", s.size));
    t.open("const FILLER: Self = Self {");
    for field in &s.fields {
        t.line(format!(
            "{}: <{} as rt::Fixed>::FILLER,",
            field.name,
            g.fixed(2, &field.ty)
        ));
    }
    t.shut("};");
    t.open("fn read(oidl_bytes: &[u8], oidl_minor: u16) -> Result<Self, rt::WireError> {");
    t.open("if oidl_bytes.len() != Self::SIZE {");
    t.line("return Err(rt::WireError::Size);");
    t.shut("}");
    for (_, step) in steps_of(s) {
        match step {
            Step::Pad(at, len) => t.line(format!("rt::check_zero(oidl_bytes, {at}, {len})?;")),
            Step::Field(f) => t.line(format!(
                "let {name}: {ty} = rt::field(oidl_bytes, {at}, {minor})?;",
                name = f.name,
                ty = g.fixed(2, &f.ty),
                at = f.offset,
                minor = Gen::minor_arg(&f.ty, &s.library, "oidl_minor"),
            )),
        }
    }
    let names: Vec<&str> = s.fields.iter().map(|f| f.name.as_str()).collect();
    t.line(format!("Ok(Self {{ {} }})", names.join(", ")));
    t.shut("}");
    t.open("fn write(self, out: &mut [u8]) -> Result<(), rt::WireError> {");
    t.open("if out.len() != Self::SIZE {");
    t.line("return Err(rt::WireError::Size);");
    t.shut("}");
    t.line("out.fill(0);");
    for field in &s.fields {
        t.line(format!(
            "rt::put_field(out, {}, self.{})?;",
            field.offset, field.name
        ));
    }
    t.line("Ok(())");
    t.shut("}");
    t.shut("}");
    t.blank();
}

fn gen_sized_struct(g: &Gen<'_>, t: &mut Text, s: &Struct, lib_version: Version) {
    let name = pascal(&s.name);
    let is_later = |since: Version| since > base(lib_version);
    t.doc(&s.doc);
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.open(format!("pub struct {name} {{"));
    for field in &s.fields {
        field_doc(t, &field.doc);
        let ty = g.fixed(2, &field.ty);
        let ty = if is_later(field.since) {
            format!("Option<{ty}>")
        } else {
            ty
        };
        t.line(format!("pub {}: {ty},", field.name));
    }
    t.shut("}");
    t.blank();
    t.open(format!("impl {name} {{"));
    t.line("/// Bytes of the newest version of this structure.");
    t.line(format!("pub const SIZE: u32 = {};", s.size));
    t.line("/// Bytes of the oldest version.");
    t.line(format!("pub const BASE_SIZE: u32 = {};", s.base_size()));
    t.line("/// The size of each version, ascending.");
    let sizes: Vec<String> = s.sizes.iter().map(|(_, size)| size.to_string()).collect();
    t.line(format!(
        "pub const SIZES: [u32; {}] = [{}];",
        sizes.len(),
        sizes.join(", ")
    ));
    t.line("/// Byte offset of `size`.");
    t.line("pub const SIZE_AT: usize = 0;");
    for field in &s.fields {
        t.line(format!("/// Byte offset of `{}`.", field.name));
        t.line(format!(
            "pub const {}_AT: usize = {};",
            shouty(&field.name),
            field.offset
        ));
    }
    t.blank();
    t.line("/// Whether the caller's `size` is valid for this structure as a parameter (§5.3).");
    t.open("pub fn accepts_param_size(size: u32) -> bool {");
    t.line("Self::SIZES.contains(&size)");
    t.shut("}");
    t.blank();
    t.line("/// Whether the caller's `size` is valid for this structure as a result (§5.3).");
    t.open("pub const fn accepts_result_size(size: u32) -> bool {");
    t.line("size >= Self::BASE_SIZE");
    t.shut("}");
    t.blank();
    t.line("/// How many bytes of this structure the server may write, given the caller's `size`.");
    t.open("pub const fn writable(size: u32) -> u32 {");
    t.line("if size < Self::SIZE { size } else { Self::SIZE }");
    t.shut("}");
    t.blank();
    t.line("/// Decodes the fields present in `size` bytes; `size` is already checked.");
    t.open("pub fn decode(oidl_bytes: &[u8], oidl_size: u32, oidl_minor: u16) -> Result<Self, rt::WireError> {");
    t.line("let oidl_len = usize::try_from(oidl_size).map_err(|_| rt::WireError::Size)?;");
    t.open("if oidl_bytes.len() < oidl_len || oidl_size < Self::BASE_SIZE {");
    t.line("return Err(rt::WireError::Size);");
    t.shut("}");
    for (_, step) in steps_of(s) {
        match step {
            Step::Pad(at, len) => {
                let needed = s
                    .sizes
                    .iter()
                    .find(|(_, size)| at < *size)
                    .map_or(s.size, |(_, size)| *size);
                if needed <= s.base_size() {
                    t.line(format!("rt::check_zero(oidl_bytes, {at}, {len})?;"));
                } else {
                    t.line(format!(
                        "if oidl_size >= {needed} {{ rt::check_zero(oidl_bytes, {at}, {len})?; }}"
                    ));
                }
            }
            Step::Field(field) => {
                let ty = g.fixed(2, &field.ty);
                let minor = Gen::minor_arg(&field.ty, &s.library, "oidl_minor");
                if is_later(field.since) {
                    let group_size = s.size_at(field.since.minor);
                    t.line(format!(
                        "let {name} = if oidl_size >= {group_size} {{ Some(rt::field::<{ty}>(oidl_bytes, {at}, {minor})?) }} else {{ None }};",
                        name = field.name,
                        at = field.offset
                    ));
                } else {
                    t.line(format!(
                        "let {name}: {ty} = rt::field(oidl_bytes, {at}, {minor})?;",
                        name = field.name,
                        at = field.offset
                    ));
                }
            }
        }
    }
    let names: Vec<&str> = s.fields.iter().map(|f| f.name.as_str()).collect();
    t.line(format!("Ok(Self {{ {} }})", names.join(", ")));
    t.shut("}");
    t.blank();
    t.line("/// Writes the fields that fit in `limit` bytes into `out`, leaving `size` alone.");
    t.open(
        "pub fn encode_fields(&self, out: &mut [u8], limit: u32) -> Result<(), rt::WireError> {",
    );
    t.open("if out.len() < usize::try_from(Self::SIZE).unwrap_or(usize::MAX) {");
    t.line("return Err(rt::WireError::Size);");
    t.shut("}");
    // Padding is written as zero wherever a caller will see it (§5.2).
    for (at, len) in &s.padding {
        let end = u64::from(*at).saturating_add(u64::from(*len));
        t.open(format!("if u64::from(limit) >= {end} {{"));
        t.line(format!("rt::zero_fill(out, {at}, {len})?;"));
        t.shut("}");
    }
    for field in &s.fields {
        let size = layout::fixed_layout(&field.ty).0;
        let end = u64::from(field.offset).saturating_add(size);
        if is_later(field.since) {
            t.open(format!(
                "if u64::from(limit) >= {end} && let Some(value) = self.{} {{",
                field.name
            ));
            t.line(format!("rt::put_field(out, {}, value)?;", field.offset));
            t.shut("}");
        } else {
            t.open(format!("if u64::from(limit) >= {end} {{"));
            t.line(format!(
                "rt::put_field(out, {}, self.{})?;",
                field.offset, field.name
            ));
            t.shut("}");
        }
    }
    t.line("Ok(())");
    t.shut("}");
    t.shut("}");
    t.blank();
}

fn gen_types(g: &Gen<'_>) -> String {
    let lib = g.lib;
    let mut t = Text::default();
    t.line("//! Types of the library.");
    t.line(SAFE_ATTRS.trim_end());
    t.blank();
    t.line("#[allow(unused_imports)]");
    t.line(format!("use {} as rt;", Gen::rt(2)));
    t.blank();
    t.line("/// This library's version: `(major, minor)` (§9).");
    t.line(format!(
        "pub const VERSION: (u16, u16) = ({}, {});",
        lib.version.major, lib.version.minor
    ));
    t.blank();
    for c in &lib.consts {
        gen_const(g, &mut t, c);
    }
    for e in &lib.enums {
        gen_enum(&mut t, e, e.name == "status");
    }
    for b in &lib.bits {
        gen_bits(&mut t, b);
    }
    for s in &lib.structs {
        if s.sized {
            gen_sized_struct(g, &mut t, s, lib.version);
        } else {
            gen_fixed_struct(g, &mut t, s);
        }
    }
    if !lib.capabilities.is_empty() {
        t.line("/// The capabilities this library's methods can require (§6).");
        t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]");
        t.line("#[non_exhaustive]");
        t.open("pub enum Capability {");
        for capability in &lib.capabilities {
            t.doc(&capability.doc);
            t.line(format!("{},", pascal(&capability.ident())));
        }
        t.shut("}");
        t.blank();
    }
    t.finish()
}

// --- Method errors -------------------------------------------------------------------------

fn gen_method_error(g: &Gen<'_>, t: &mut Text, method: &Method) {
    if method.oneway || method.never {
        return;
    }
    let name = format!("{}Error", pascal(&method.name));
    let status = g.status_path(3);
    t.line(format!("/// What `{}` can fail with.", method.name));
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.line("#[non_exhaustive]");
    t.open(format!("pub enum {name} {{"));
    for error in &method.errors {
        t.line(format!("/// `{}`.", shouty(&error.name)));
        t.line(format!("{},", pascal(&error.name)));
    }
    t.shut("}");
    t.blank();
    t.open(format!("impl {name} {{"));
    t.line("/// The status this error is reported as.");
    t.open(format!("pub const fn error(self) -> {status} {{"));
    if method.errors.is_empty() {
        t.line("match self {}");
    } else {
        t.open("match self {");
        for error in &method.errors {
            t.line(format!(
                "Self::{} => {status}::{},",
                pascal(&error.name),
                pascal(&error.name)
            ));
        }
        t.shut("}");
    }
    t.shut("}");
    t.shut("}");
    t.blank();
    t.open(format!("impl rt::MethodError for {name} {{"));
    t.open("fn from_status(status: i64) -> Option<Self> {");
    if method.errors.is_empty() {
        t.line("let _ = status;");
        t.line("None");
    } else {
        t.open(format!("match {status}::from_raw(status)? {{"));
        for error in &method.errors {
            t.line(format!(
                "{status}::{variant} => Some(Self::{variant}),",
                variant = pascal(&error.name)
            ));
        }
        t.line("_ => None,");
        t.shut("}");
    }
    t.shut("}");
    t.open("fn status(self) -> i64 {");
    t.line("self.error().raw()");
    t.shut("}");
    t.shut("}");
    t.blank();
}

// --- System-call transport ---------------------------------------------------------------

/// A method's generated server-side argument type (§10).
fn sys_server_ty(g: &Gen<'_>, p: &Param, is_result: bool) -> String {
    match &p.ty {
        Type::Handle(h) => {
            if is_result {
                "rt::UserRef<rt::Handle>".to_string()
            } else if h.optional {
                "Option<rt::HandleArg>".to_string()
            } else {
                "rt::HandleArg".to_string()
            }
        }
        Type::Vector(elem, _) => {
            if is_result {
                match elem.as_ref() {
                    Type::Handle(_) => "rt::UserBuffer<rt::Handle>".to_string(),
                    other => format!("rt::UserBuffer<{}>", g.fixed(3, other)),
                }
            } else {
                match elem.as_ref() {
                    Type::Handle(_) => "rt::HandleSlice".to_string(),
                    other => format!("rt::UserSlice<{}>", g.fixed(3, other)),
                }
            }
        }
        Type::String(_) => {
            if is_result {
                "rt::UserBuffer<u8>".to_string()
            } else {
                "rt::UserSlice<u8>".to_string()
            }
        }
        Type::Struct(s) => format!("rt::UserRef<{}>", g.path(3, &s.library, &pascal(&s.name))),
        Type::Array(elem, count) => match elem.as_ref() {
            Type::Handle(_) => format!("rt::UserRef<[rt::Handle; {count}]>"),
            other => format!("rt::UserRef<[{}; {count}]>", g.fixed(3, other)),
        },
        other => {
            let ty = g.fixed(3, other);
            if is_result {
                format!("rt::UserRef<{ty}>")
            } else {
                ty
            }
        }
    }
}

fn gen_sys_decode(g: &Gen<'_>, t: &mut Text, method: &Method) {
    let error = format!("{}Error", pascal(&method.name));
    let mut index = 0usize;
    let reg = |i: usize| format!("oidl_a{i}");
    let mut names = Vec::new();
    for param in &method.params {
        names.push(param.name.clone());
        match &param.ty {
            Type::Handle(h) => {
                let a = reg(index);
                index = index.saturating_add(1);
                let (need_rights, need_object) = (h.rights_mask, h.object_value);
                if h.optional {
                    t.line(format!(
                        "let {name} = if {a} == 0 {{ None }} else {{ Some(rt::HandleArg::from_reg({a}, {need_rights:#x}, {need_object}).ok_or({error}::BadHandle)?) }};",
                        name = param.name
                    ));
                } else {
                    t.line(format!(
                        "let {name} = rt::HandleArg::from_reg({a}, {need_rights:#x}, {need_object}).ok_or({error}::BadHandle)?;",
                        name = param.name
                    ));
                }
            }
            Type::Bool => {
                let a = reg(index);
                index = index.saturating_add(1);
                t.line(format!(
                    "let {name} = u8::try_from({a}).ok().and_then(rt::decode_bool).ok_or({error}::InvalidArgs)?;",
                    name = param.name
                ));
            }
            Type::Int(int) => {
                let a = reg(index);
                index = index.saturating_add(1);
                let ty = int.rust();
                let decode = match (int.is_64(), int.signed()) {
                    (true, false) => a.clone(),
                    (true, true) => format!("{a} as i64"),
                    (false, false) => {
                        format!("{ty}::try_from({a}).map_err(|_| {error}::InvalidArgs)?")
                    }
                    (false, true) => {
                        format!("{ty}::try_from({a} as i64).map_err(|_| {error}::InvalidArgs)?")
                    }
                };
                t.line(format!("let {}: {ty} = {decode};", param.name));
                if param.nonzero {
                    t.open(format!("if {} == 0 {{", param.name));
                    t.line(format!("return Err({error}::InvalidArgs);"));
                    t.shut("}");
                }
            }
            Type::Enum(e) => {
                let a = reg(index);
                index = index.saturating_add(1);
                let name = g.path(3, &e.library, &enum_name(e));
                let repr = e.repr.rust();
                let raw = if e.repr.is_64() {
                    format!("Some({a} as {repr})")
                } else if e.repr.signed() {
                    format!("{repr}::try_from({a} as i64).ok()")
                } else {
                    format!("{repr}::try_from({a}).ok()")
                };
                t.line(format!(
                    "let {pname} = {raw}.and_then({name}::from_raw).ok_or({error}::InvalidArgs)?;",
                    pname = param.name
                ));
            }
            Type::Bits(b) => {
                let a = reg(index);
                index = index.saturating_add(1);
                let name = g.path(3, &b.library, &pascal(&b.name));
                let repr = b.repr.rust();
                let raw = if b.repr.is_64() {
                    format!("Some({a})")
                } else {
                    format!("{repr}::try_from({a}).ok()")
                };
                t.line(format!(
                    "let {pname} = {raw}.and_then({name}::from_bits).ok_or({error}::InvalidArgs)?;",
                    pname = param.name
                ));
                if param.nonzero {
                    t.open(format!("if {}.bits() == 0 {{", param.name));
                    t.line(format!("return Err({error}::InvalidArgs);"));
                    t.shut("}");
                }
            }
            Type::Struct(s) => {
                let a = reg(index);
                index = index.saturating_add(1);
                let name = g.path(3, &s.library, &pascal(&s.name));
                t.line(format!(
                    "let {pname} = rt::UserRef::<{name}>::new({a});",
                    pname = param.name
                ));
            }
            Type::Array(elem, count) => {
                let a = reg(index);
                index = index.saturating_add(1);
                let inner = match elem.as_ref() {
                    Type::Handle(_) => "rt::Handle".to_string(),
                    other => g.fixed(3, other),
                };
                t.line(format!(
                    "let {pname} = rt::UserRef::<[{inner}; {count}]>::new({a});",
                    pname = param.name
                ));
            }
            Type::Vector(elem, bound) => {
                let (a, b) = (reg(index), reg(index.saturating_add(1)));
                index = index.saturating_add(2);
                match elem.as_ref() {
                    Type::Handle(h) => {
                        t.line(format!(
                            "let {pname} = rt::UserSlice::<rt::Handle>::new({a}, {b}, {bound}).map(|slice| rt::HandleSlice {{ slice, need_rights: {rights:#x}, need_object: {object} }}).ok_or({error}::InvalidArgs)?;",
                            pname = param.name,
                            rights = h.rights_mask,
                            object = h.object_value
                        ));
                    }
                    other => {
                        t.line(format!(
                            "let {pname} = rt::UserSlice::<{inner}>::new({a}, {b}, {bound}).ok_or({error}::InvalidArgs)?;",
                            pname = param.name,
                            inner = g.fixed(3, other)
                        ));
                    }
                }
            }
            Type::String(bound) => {
                let (a, b) = (reg(index), reg(index.saturating_add(1)));
                index = index.saturating_add(2);
                t.line(format!(
                    "let {pname} = rt::UserSlice::<u8>::new({a}, {b}, {bound}).ok_or({error}::InvalidArgs)?;",
                    pname = param.name
                ));
            }
        }
    }
    for result in &method.returns {
        names.push(result.name.clone());
        match &result.ty {
            Type::Vector(elem, bound) => {
                let (a, b) = (reg(index), reg(index.saturating_add(1)));
                index = index.saturating_add(2);
                let inner = match elem.as_ref() {
                    Type::Handle(_) => "rt::Handle".to_string(),
                    other => g.fixed(3, other),
                };
                t.line(format!(
                    "let {rname} = rt::UserBuffer::<{inner}>::new({a}, {b}, {bound});",
                    rname = result.name
                ));
            }
            Type::String(bound) => {
                let (a, b) = (reg(index), reg(index.saturating_add(1)));
                index = index.saturating_add(2);
                t.line(format!(
                    "let {rname} = rt::UserBuffer::<u8>::new({a}, {b}, {bound});",
                    rname = result.name
                ));
            }
            _ => {
                let a = reg(index);
                index = index.saturating_add(1);
                t.line(format!(
                    "let {rname} = rt::UserRef::new({a});",
                    rname = result.name
                ));
            }
        }
    }
    t.line(format!("oidl_calls.{}({})", method.name, names.join(", ")));
}

fn gen_sys_server(g: &Gen<'_>, interface: &Interface) -> String {
    let mut t = Text::default();
    let status = g.status_path(3);
    t.line("//! Kernel side: the call table, per-method errors, the argument decoders and `dispatch` (§10).");
    t.line(SAFE_ATTRS.trim_end());
    t.blank();
    t.line(format!("use {} as rt;", Gen::rt(3)));
    t.line("#[allow(unused_imports)]");
    t.line("use super::super::types::*;");
    t.blank();
    t.line("/// System-call numbers: private to this release (§42).");
    t.open("pub mod number {");
    for method in &interface.methods {
        t.line(format!("/// `{}`.", method.name));
        t.line(format!(
            "pub const {}: u64 = {};",
            shouty(&method.name),
            method.ordinal
        ));
    }
    t.shut("}");
    t.blank();
    t.line("/// One entry of the call table.");
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.open("pub struct CallInfo {");
    t.line("/// The call number.");
    t.line("pub number: u64,");
    t.line("/// The method's name.");
    t.line("pub name: &'static str,");
    t.line("/// Argument registers it uses.");
    t.line("pub registers: u32,");
    t.line("/// Whether it is `@reserved`: the number exists but no implementation does.");
    t.line("pub reserved: bool,");
    t.shut("}");
    t.blank();
    t.line("/// Every call, in number order.");
    t.line(format!(
        "pub const CALLS: [CallInfo; {}] = [",
        interface.methods.len()
    ));
    for method in &interface.methods {
        let registers: u32 = method
            .params
            .iter()
            .chain(&method.returns)
            .map(|p| crate::sema::registers_of(&p.ty))
            .fold(0, u32::saturating_add);
        t.line(format!(
            "    CallInfo {{ number: {}, name: \"{}\", registers: {registers}, reserved: {} }},",
            method.ordinal, method.name, method.reserved
        ));
    }
    t.line("];");
    t.blank();
    for method in &interface.methods {
        gen_method_error(g, &mut t, method);
    }
    t.line("/// What a call left to do on its way out of the kernel.");
    t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    t.open("pub enum Outcome {");
    t.line("/// Return this status in RAX.");
    t.line("Status(i64),");
    t.line("/// The thread is over.");
    t.line("ThreadExit,");
    t.shut("}");
    t.blank();
    t.line("/// The kernel's implementation of the interface.");
    t.open("pub trait Calls {");
    if !g.lib.capabilities.is_empty() {
        t.line("/// Whether the calling process holds this capability.");
        t.line("fn holds(&self, capability: Capability) -> bool;");
    }
    for method in &interface.methods {
        if method.reserved {
            continue;
        }
        t.doc(&method.doc);
        let mut args = vec!["&self".to_string()];
        for param in &method.params {
            args.push(format!(
                "{}: {}",
                param.name,
                sys_server_ty(g, param, false)
            ));
        }
        for result in &method.returns {
            args.push(format!(
                "{}: {}",
                result.name,
                sys_server_ty(g, result, true)
            ));
        }
        if method.never {
            t.line(format!("fn {}({});", method.name, args.join(", ")));
        } else {
            t.line(format!(
                "fn {}({}) -> Result<(), {}Error>;",
                method.name,
                args.join(", "),
                pascal(&method.name)
            ));
        }
    }
    t.shut("}");
    t.blank();
    t.line("/// Decodes and runs one system call: the number and its six arguments.");
    t.open("pub fn dispatch<C: Calls + ?Sized>(oidl_calls: &C, oidl_number: u64, oidl_args: [u64; 6]) -> Outcome {");
    t.open("let oidl_status = match oidl_number {");
    for method in &interface.methods {
        if method.reserved {
            t.line(format!(
                "number::{} => {status}::NotSupported.raw(),",
                shouty(&method.name)
            ));
        } else if method.never {
            t.open(format!("number::{} => {{", shouty(&method.name)));
            let decl: Vec<String> = (0..6)
                .map(|i| {
                    if i < method.params.len() {
                        format!("oidl_a{i}")
                    } else {
                        "_".to_string()
                    }
                })
                .collect();
            t.line(format!("let [{}] = oidl_args;", decl.join(", ")));
            let names: Vec<String> = method
                .params
                .iter()
                .enumerate()
                .map(|(i, _)| format!("oidl_a{i}"))
                .collect();
            t.line(format!("oidl_calls.{}({});", method.name, names.join(", ")));
            t.line("return Outcome::ThreadExit;");
            t.shut("}");
        } else {
            t.line(format!(
                "number::{} => match call_{}(oidl_calls, oidl_args) {{ Ok(()) => 0, Err(oidl_e) => oidl_e.error().raw() }},",
                shouty(&method.name),
                method.name
            ));
        }
    }
    t.line(format!("_ => {status}::NotSupported.raw(),"));
    t.shut("};");
    t.line("Outcome::Status(oidl_status)");
    t.shut("}");
    t.blank();
    for method in &interface.methods {
        if method.reserved || method.never {
            continue;
        }
        let error = format!("{}Error", pascal(&method.name));
        t.open(format!(
            "fn call_{}<C: Calls + ?Sized>(oidl_calls: &C, oidl_args: [u64; 6]) -> Result<(), {error}> {{",
            method.name
        ));
        let used: u32 = method
            .params
            .iter()
            .chain(&method.returns)
            .map(|p| crate::sema::registers_of(&p.ty))
            .fold(0, u32::saturating_add);
        let names: Vec<String> = (0..6u32)
            .map(|i| {
                if i < used {
                    format!("oidl_a{i}")
                } else {
                    "_".to_string()
                }
            })
            .collect();
        t.line(format!("let [{}] = oidl_args;", names.join(", ")));
        if let Some(requirement) = &method.requires {
            t.open(format!(
                "if !oidl_calls.holds(Capability::{}) {{",
                pascal(&requirement.capability.ident())
            ));
            t.line(format!(
                "return Err({error}::{});",
                pascal(&requirement.denied.name)
            ));
            t.shut("}");
        }
        gen_sys_decode(g, &mut t, method);
        t.shut("}");
        t.blank();
    }
    t.finish()
}

/// The Rust type of a parameter of the safe client.
fn client_ty(g: &Gen<'_>, p: &Param) -> String {
    match &p.ty {
        Type::Handle(h) => {
            if h.optional {
                "Option<rt::Handle>".to_string()
            } else {
                "rt::Handle".to_string()
            }
        }
        Type::Vector(elem, _) => match elem.as_ref() {
            Type::Handle(_) => "&[rt::Handle]".to_string(),
            other => format!("&[{}]", g.fixed(3, other)),
        },
        Type::String(_) => "&str".to_string(),
        Type::Struct(s) => format!("&{}", g.path(3, &s.library, &pascal(&s.name))),
        Type::Array(elem, count) => match elem.as_ref() {
            Type::Handle(_) => format!("&[rt::Handle; {count}]"),
            other => format!("&[{}; {count}]", g.fixed(3, other)),
        },
        other => g.fixed(3, other),
    }
}

/// The Rust type of a result value of the safe client.
fn client_result_ty(g: &Gen<'_>, p: &Param) -> String {
    match &p.ty {
        Type::Handle(h) => {
            if h.optional {
                "Option<rt::Handle>".to_string()
            } else {
                "rt::Handle".to_string()
            }
        }
        Type::Vector(..) | Type::String(_) => "usize".to_string(),
        Type::Struct(s) => g.path(3, &s.library, &pascal(&s.name)),
        Type::Array(elem, count) => match elem.as_ref() {
            Type::Handle(_) => format!("[rt::Handle; {count}]"),
            other => format!("[{}; {count}]", g.fixed(3, other)),
        },
        other => g.fixed(3, other),
    }
}

fn has_also_on(method: &Method) -> bool {
    method.returns.iter().any(|r| !r.also_on.is_empty())
}

fn abi_scalar(g: &Gen<'_>, ty: &Type) -> String {
    match ty {
        Type::Bool => "u8".to_string(),
        Type::Int(int) => int.rust().to_string(),
        Type::Enum(e) => e.repr.rust().to_string(),
        Type::Bits(b) => b.repr.rust().to_string(),
        Type::Handle(_) => "u32".to_string(),
        other => g.fixed(3, other),
    }
}

fn abi_element(ty: &Type) -> String {
    match ty {
        Type::Handle(_) => "u32".to_string(),
        Type::Int(int) => int.rust().to_string(),
        _ => "u8".to_string(),
    }
}

/// The size of a struct element of a `syscall` vector or array, which crosses as bytes encoded
/// field by field (§10, ADR-0005 C3); `None` for an integer or a handle, which crosses as its
/// in-memory form.
fn record_size(elem: &Type) -> Option<u64> {
    match elem {
        Type::Struct(s) => Some(u64::from(s.size)),
        _ => None,
    }
}

/// One abi-level parameter: `(name, Rust type, conversion to u64 for the stub)`.
fn abi_params(g: &Gen<'_>, method: &Method) -> Vec<(String, String, &'static str)> {
    let mut out = Vec::new();
    for param in &method.params {
        let n = param.name.clone();
        match &param.ty {
            Type::Struct(_) => out.push((n, "*const u8".to_string(), "ptr")),
            Type::Array(elem, _) => out.push((n, format!("*const {}", abi_element(elem)), "ptr")),
            Type::Vector(elem, _) => {
                out.push((n.clone(), format!("*const {}", abi_element(elem)), "ptr"));
                out.push((format!("{n}_count"), "u64".to_string(), "u"));
            }
            Type::String(_) => {
                out.push((n.clone(), "*const u8".to_string(), "ptr"));
                out.push((format!("{n}_count"), "u64".to_string(), "u"));
            }
            scalar => {
                let ty = abi_scalar(g, scalar);
                let conv = match scalar {
                    Type::Int(int) if int.signed() => "s",
                    Type::Enum(e) if e.repr.signed() => "s",
                    _ => "u",
                };
                out.push((n, ty, conv));
            }
        }
    }
    for result in &method.returns {
        let n = result.name.clone();
        match &result.ty {
            Type::Struct(_) => out.push((n, "*mut u8".to_string(), "ptr")),
            Type::Array(elem, _) => out.push((n, format!("*mut {}", abi_element(elem)), "ptr")),
            Type::Vector(elem, _) => {
                out.push((n.clone(), format!("*mut {}", abi_element(elem)), "ptr"));
                out.push((format!("{n}_capacity"), "u64".to_string(), "u"));
            }
            Type::String(_) => {
                out.push((n.clone(), "*mut u8".to_string(), "ptr"));
                out.push((format!("{n}_capacity"), "u64".to_string(), "u"));
            }
            scalar => {
                let ty = abi_scalar(g, scalar);
                out.push((n, format!("*mut {ty}"), "ptr"));
            }
        }
    }
    out
}

fn gen_sys_abi(g: &Gen<'_>, interface: &Interface) -> String {
    let mut t = Text::default();
    let prefix = g.c_prefix();
    t.line("//! The named shim: C-ABI imports and the only `unsafe` the safe client reaches (ADR-0011 S7).");
    t.line(format!(
        "#[allow(unused_imports)]\nuse {} as rt;",
        Gen::rt(3)
    ));
    t.blank();
    t.open("unsafe extern \"C\" {");
    for method in &interface.methods {
        let params: Vec<String> = abi_params(g, method)
            .into_iter()
            .map(|(n, ty, _)| format!("{n}: {ty}"))
            .collect();
        if method.never {
            t.line(format!(
                "fn {prefix}_{}({}) -> !;",
                method.name,
                params.join(", ")
            ));
        } else {
            t.line(format!(
                "fn {prefix}_{}({}) -> i64;",
                method.name,
                params.join(", ")
            ));
        }
    }
    t.shut("}");
    t.blank();
    for method in &interface.methods {
        // The safe wrapper takes references, so a caller cannot pass a bad pointer.
        let mut args = Vec::new();
        let mut call = Vec::new();
        for param in &method.params {
            let n = &param.name;
            match &param.ty {
                Type::Struct(s) => {
                    args.push(format!("{n}: &rt::Aligned<{}>", s.size));
                    call.push(format!("{n}.0.as_ptr()"));
                }
                Type::Array(elem, count) => {
                    let e = abi_element(elem);
                    match record_size(elem) {
                        Some(size) => {
                            let bytes = u64::from(*count).saturating_mul(size);
                            args.push(format!("{n}: &[u8; {bytes}]"));
                        }
                        None => args.push(format!("{n}: &[{e}; {count}]")),
                    }
                    call.push(format!("{n}.as_ptr()"));
                }
                Type::Vector(elem, _) => {
                    let e = abi_element(elem);
                    if let Some(size) = record_size(elem) {
                        // Encoded records: the count is in elements, never more than the
                        // bytes passed hold.
                        args.push(format!("{n}: &[u8]"));
                        call.push(format!("{n}.as_ptr()"));
                        call.push(format!("{n}.len().checked_div({size}).unwrap_or(0) as u64"));
                    } else {
                        let t = match elem.as_ref() {
                            Type::Handle(_) => "rt::Handle".to_string(),
                            _ => e.clone(),
                        };
                        args.push(format!("{n}: &[{t}]"));
                        call.push(format!("{n}.as_ptr().cast::<{e}>()"));
                        call.push(format!("{n}.len() as u64"));
                    }
                }
                Type::String(_) => {
                    args.push(format!("{n}: &str"));
                    call.push(format!("{n}.as_ptr()"));
                    call.push(format!("{n}.len() as u64"));
                }
                scalar => {
                    args.push(format!("{n}: {}", abi_scalar(g, scalar)));
                    call.push(n.clone());
                }
            }
        }
        for result in &method.returns {
            let n = &result.name;
            match &result.ty {
                Type::Struct(s) => {
                    args.push(format!("{n}: &mut rt::Aligned<{}>", s.size));
                    call.push(format!("{n}.0.as_mut_ptr()"));
                }
                Type::Array(elem, count) => {
                    let e = abi_element(elem);
                    if let Some(size) = record_size(elem) {
                        let bytes = u64::from(*count).saturating_mul(size);
                        args.push(format!("{n}: &mut [u8; {bytes}]"));
                        call.push(format!("{n}.as_mut_ptr()"));
                    } else {
                        let t = match elem.as_ref() {
                            Type::Handle(_) => "rt::Handle".to_string(),
                            _ => e.clone(),
                        };
                        args.push(format!("{n}: &mut [{t}; {count}]"));
                        call.push(format!("{n}.as_mut_ptr().cast::<{e}>()"));
                    }
                }
                Type::Vector(elem, _) => {
                    let e = abi_element(elem);
                    if let Some(size) = record_size(elem) {
                        // Room for encoded records: the capacity is in elements, never more
                        // than the bytes passed hold.
                        args.push(format!("{n}: &mut [u8]"));
                        call.push(format!("{n}.as_mut_ptr()"));
                        call.push(format!("{n}.len().checked_div({size}).unwrap_or(0) as u64"));
                    } else {
                        let t = match elem.as_ref() {
                            Type::Handle(_) => "rt::Handle".to_string(),
                            _ => e.clone(),
                        };
                        args.push(format!("{n}: &mut [{t}]"));
                        call.push(format!("{n}.as_mut_ptr().cast::<{e}>()"));
                        call.push(format!("{n}.len() as u64"));
                    }
                }
                Type::String(_) => {
                    args.push(format!("{n}: &mut [u8]"));
                    call.push(format!("{n}.as_mut_ptr()"));
                    call.push(format!("{n}.len() as u64"));
                }
                scalar => {
                    let ty = match scalar {
                        Type::Handle(_) => "rt::Handle".to_string(),
                        other => abi_scalar(g, other),
                    };
                    args.push(format!("{n}: &mut {ty}"));
                    let abi_ty = abi_scalar(g, scalar);
                    call.push(format!("core::ptr::from_mut({n}).cast::<{abi_ty}>()"));
                }
            }
        }
        let result = if method.never { "!" } else { "i64" };
        t.open(format!(
            "pub(super) fn {}({}) -> {result} {{",
            method.name,
            args.join(", ")
        ));
        t.line(
            "// SAFETY: every pointer comes from a live borrow of the size passed, and the kernel",
        );
        t.line(
            "// checks each one against the caller's own tables before it is used (ADR-0005 P4).",
        );
        t.line(format!(
            "unsafe {{ {prefix}_{}({}) }}",
            method.name,
            call.join(", ")
        ));
        t.shut("}");
        t.blank();
    }
    t.finish()
}

fn gen_sys_client(g: &Gen<'_>, interface: &Interface) -> String {
    let mut t = Text::default();
    t.line("//! Safe client of the interface (§11). No `unsafe` here: it reaches the kernel through `abi`.");
    t.line(SAFE_ATTRS.trim_end());
    t.blank();
    t.line(format!("use {} as rt;", Gen::rt(3)));
    t.line("#[allow(unused_imports)]");
    t.line("use super::super::types::*;");
    t.line("#[allow(unused_imports)]");
    t.line("use super::server::*;");
    t.line("use super::abi;");
    t.blank();
    for method in &interface.methods {
        gen_sys_client_method(g, &mut t, method);
    }
    t.finish()
}

fn gen_sys_client_method(g: &Gen<'_>, t: &mut Text, method: &Method) {
    let base_name = pascal(&method.name);
    if method.never {
        t.doc(&method.doc);
        let args: Vec<String> = method
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, client_ty(g, p)))
            .collect();
        t.open(format!(
            "pub fn {}({}) -> ! {{",
            method.name,
            args.join(", ")
        ));
        let call: Vec<String> = method.params.iter().map(sys_client_value).collect();
        t.line(format!("abi::{}({})", method.name, call.join(", ")));
        t.shut("}");
        t.blank();
        return;
    }
    let also_on = has_also_on(method);
    let error = format!("{base_name}Error");
    // Optional result structs (`Out`, `Failure`).
    let returned: Vec<&Param> = method.returns.iter().collect();
    let out_ty = match returned.as_slice() {
        [] => "()".to_string(),
        [single] if !matches!(single.ty, Type::Vector(..) | Type::String(_)) => {
            client_result_ty(g, single)
        }
        _ => format!("{base_name}Out"),
    };
    if out_ty == format!("{base_name}Out") {
        t.line(format!("/// What `{}` returns.", method.name));
        t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
        t.open(format!("pub struct {base_name}Out {{"));
        for result in &returned {
            t.doc(&result.doc);
            t.line(format!(
                "pub {}: {},",
                result.name,
                client_result_ty(g, result)
            ));
        }
        t.shut("}");
        t.blank();
    }
    let failure = format!("{base_name}Failure");
    if also_on {
        t.line(format!(
            "/// How `{}` failed, with what it still wrote.",
            method.name
        ));
        t.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
        t.open(format!("pub struct {failure} {{"));
        t.line("/// The error.");
        t.line(format!("pub error: {error},"));
        for result in &returned {
            if !result.also_on.is_empty() {
                t.line(format!("/// `{}`, if this error writes it.", result.name));
                t.line(format!(
                    "pub {}: Option<{}>,",
                    result.name,
                    client_result_ty(g, result)
                ));
            }
        }
        t.shut("}");
        t.blank();
    }
    let mut args: Vec<String> = method
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name, client_ty(g, p)))
        .collect();
    for result in &returned {
        match &result.ty {
            Type::Vector(elem, _) => {
                let inner = match elem.as_ref() {
                    Type::Handle(_) => "rt::Handle".to_string(),
                    other => g.fixed(3, other),
                };
                args.push(format!("{}: &mut [{inner}]", result.name));
            }
            Type::String(_) => args.push(format!("{}: &mut [u8]", result.name)),
            _ => {}
        }
    }
    let error_ty = if also_on {
        failure.clone()
    } else {
        error.clone()
    };
    t.doc(&method.doc);
    t.open(format!(
        "pub fn {}({}) -> Result<{out_ty}, rt::CallError<{error_ty}>> {{",
        method.name,
        args.join(", ")
    ));
    // Encode structs passed by value.
    for param in &method.params {
        if let Type::Struct(s) = &param.ty {
            t.line(format!(
                "let mut oidl_buf_{} = rt::Aligned::<{}>::new();",
                param.name, s.size
            ));
            if s.sized {
                t.line(format!(
                    "rt::put_field(&mut oidl_buf_{name}.0, 0, {size}u32).map_err(rt::CallError::Protocol)?;",
                    name = param.name,
                    size = s.size
                ));
                t.line(format!(
                    "{name}.encode_fields(&mut oidl_buf_{name}.0, {size}).map_err(rt::CallError::Protocol)?;",
                    name = param.name,
                    size = s.size
                ));
            } else {
                t.line(format!(
                    "rt::Fixed::write(*{name}, &mut oidl_buf_{name}.0).map_err(rt::CallError::Protocol)?;",
                    name = param.name
                ));
            }
        }
    }
    // Encode vectors and arrays of structs, element by element (C3).
    for param in &method.params {
        let name = &param.name;
        match &param.ty {
            Type::Vector(elem, bound) => {
                if let Some(size) = record_size(elem) {
                    let bytes = u64::from(*bound).saturating_mul(size);
                    t.line(format!("let mut oidl_buf_{name} = [0u8; {bytes}];"));
                    t.line(format!(
                        "let oidl_wire_{name} = rt::encode_elements({name}, &mut oidl_buf_{name}).map_err(rt::CallError::Protocol)?;"
                    ));
                }
            }
            Type::Array(elem, count) => {
                if let Some(size) = record_size(elem) {
                    let bytes = u64::from(*count).saturating_mul(size);
                    t.line(format!("let mut oidl_buf_{name} = [0u8; {bytes}];"));
                    t.line(format!(
                        "rt::Fixed::write(*{name}, &mut oidl_buf_{name}).map_err(rt::CallError::Protocol)?;"
                    ));
                }
            }
            _ => {}
        }
    }
    // Result storage.
    for result in &returned {
        match &result.ty {
            Type::Struct(s) => {
                t.line(format!(
                    "let mut oidl_{} = rt::Aligned::<{}>::new();",
                    result.name, s.size
                ));
                if s.sized {
                    t.line(format!(
                        "rt::put_field(&mut oidl_{name}.0, 0, {size}u32).map_err(rt::CallError::Protocol)?;",
                        name = result.name,
                        size = s.size
                    ));
                }
            }
            Type::Handle(_) => {
                t.line(format!(
                    "let mut oidl_{} = rt::Handle::INVALID;",
                    result.name
                ));
            }
            Type::Array(elem, count) => match (elem.as_ref(), record_size(elem)) {
                (Type::Handle(_), _) => t.line(format!(
                    "let mut oidl_{} = [rt::Handle::INVALID; {count}];",
                    result.name
                )),
                (_, Some(size)) => {
                    let bytes = u64::from(*count).saturating_mul(size);
                    t.line(format!("let mut oidl_{} = [0u8; {bytes}];", result.name));
                }
                _ => t.line(format!("let mut oidl_{} = [0; {count}];", result.name)),
            },
            Type::Vector(elem, bound) => {
                // Structs arrive encoded, into room here, and are decoded into the caller's
                // slice after the call.
                if let Some(size) = record_size(elem) {
                    let bytes = u64::from(*bound).saturating_mul(size);
                    t.line(format!(
                        "let mut oidl_raw_{} = [0u8; {bytes}];",
                        result.name
                    ));
                }
            }
            Type::String(_) => {}
            Type::Bool => t.line(format!("let mut oidl_{}: u8 = 0;", result.name)),
            Type::Int(_) | Type::Enum(_) | Type::Bits(_) => {
                t.line(format!(
                    "let mut oidl_{}: {} = 0;",
                    result.name,
                    abi_scalar(g, &result.ty)
                ));
            }
        }
    }
    let mut call = Vec::new();
    for param in &method.params {
        call.push(sys_client_value(param));
    }
    for result in &returned {
        call.push(match &result.ty {
            Type::Vector(elem, _) if record_size(elem).is_some() => format!(
                "rt::element_room::<{}>(&mut oidl_raw_{name}, {name}.len())",
                g.fixed(3, elem),
                name = result.name
            ),
            Type::Vector(..) | Type::String(_) => format!("&mut *{}", result.name),
            _ => format!("&mut oidl_{}", result.name),
        });
    }
    t.line(format!(
        "let oidl_status = abi::{}({});",
        method.name,
        call.join(", ")
    ));
    if also_on {
        t.open("if oidl_status != 0 {");
        t.open(format!(
            "let Some(oidl_error) = <{error} as rt::MethodError>::from_status(oidl_status) else {{"
        ));
        t.line("return Err(rt::CallError::Undeclared(oidl_status));");
        t.shut("};");
        let mut fields = vec!["error: oidl_error".to_string()];
        for result in &returned {
            if result.also_on.is_empty() {
                continue;
            }
            let variants: Vec<String> = result
                .also_on
                .iter()
                .map(|e| format!("{error}::{}", pascal(e)))
                .collect();
            let value = sys_client_result_value(g, result, false);
            t.line(format!(
                "let {name} = if matches!(oidl_error, {patterns}) {{ {value}.ok() }} else {{ None }};",
                name = result.name,
                patterns = variants.join(" | ")
            ));
            fields.push(result.name.clone());
        }
        t.line(format!(
            "return Err(rt::CallError::Method({failure} {{ {} }}));",
            fields.join(", ")
        ));
        t.shut("}");
    } else {
        t.line(format!("rt::check_status::<{error}>(oidl_status)?;"));
    }
    // A struct result is decoded here so `@count` can read it.
    for result in &returned {
        if let Type::Struct(s) = &result.ty {
            let path = g.path(3, &s.library, &pascal(&s.name));
            let name = &result.name;
            let decode = if s.sized {
                format!("{path}::decode(&oidl_{name}.0, {}, u16::MAX)", s.size)
            } else {
                format!("<{path} as rt::Fixed>::read(&oidl_{name}.0, u16::MAX)")
            };
            t.line(format!(
                "let oidl_{name}_decoded = {decode}.map_err(rt::CallError::Protocol)?;"
            ));
        }
    }
    // Then structs that arrived encoded go into the caller's slice, each one checked.
    for result in &returned {
        if let Type::Vector(elem, bound) = &result.ty
            && record_size(elem).is_some()
        {
            let name = &result.name;
            t.line(format!(
                "let oidl_{name}_count = {}.min({name}.len()).min({bound});",
                result_count(result)
            ));
            t.line(format!(
                "rt::decode_elements(&oidl_raw_{name}, {name}, oidl_{name}_count, u16::MAX).map_err(rt::CallError::Protocol)?;"
            ));
        }
    }
    match returned.as_slice() {
        [] => t.line("Ok(())"),
        [single] if !matches!(single.ty, Type::Vector(..) | Type::String(_)) => {
            let value = sys_client_result_value(g, single, true);
            t.line(format!("Ok({value})"));
        }
        _ => {
            let mut fields = Vec::new();
            for result in &returned {
                let value = sys_client_result_value(g, result, true);
                fields.push(format!("{}: {value}", result.name));
            }
            t.line(format!("Ok({base_name}Out {{ {} }})", fields.join(", ")));
        }
    }
    t.shut("}");
    t.blank();
}

/// The count a `vector` or `string` result reports through its `@count` field.
fn result_count(r: &Param) -> String {
    match &r.count {
        Some((result, field)) => {
            format!("usize::try_from(oidl_{result}_decoded.{field}).unwrap_or(usize::MAX)")
        }
        None => "0".to_string(),
    }
}

fn sys_client_value(p: &Param) -> String {
    match &p.ty {
        Type::Vector(elem, _) if record_size(elem).is_some() => format!("oidl_wire_{}", p.name),
        Type::Array(elem, _) if record_size(elem).is_some() => format!("&oidl_buf_{}", p.name),
        Type::Handle(h) => {
            if h.optional {
                format!("{}.map_or(0, |h| h.to_abi())", p.name)
            } else {
                format!("{}.to_abi()", p.name)
            }
        }
        Type::Bool => format!("u8::from({})", p.name),
        Type::Enum(_) => format!("{}.raw()", p.name),
        Type::Bits(_) => format!("{}.bits()", p.name),
        Type::Struct(_) => format!("&oidl_buf_{}", p.name),
        Type::Array(elem, _) if matches!(elem.as_ref(), Type::Handle(_)) => {
            format!("&(*{}).map(rt::Handle::to_abi)", p.name)
        }
        other => {
            let _ = other;
            p.name.clone()
        }
    }
}

/// The expression for a result value after a call. With `checked` a decode failure returns a
/// protocol error; otherwise the expression is a `Result` for `.ok()`.
fn sys_client_result_value(g: &Gen<'_>, r: &Param, checked: bool) -> String {
    let local = format!("oidl_{}", r.name);
    let finish = |expr: String| {
        if checked {
            format!("{expr}.map_err(rt::CallError::Protocol)?")
        } else {
            expr
        }
    };
    match &r.ty {
        Type::Handle(h) if h.optional => {
            let value = format!("if {local}.is_valid() {{ Some({local}) }} else {{ None }}");
            if checked {
                value
            } else {
                format!("Ok::<_, rt::WireError>({value})")
            }
        }
        Type::Handle(_) => {
            if checked {
                local
            } else {
                format!("Ok::<_, rt::WireError>({local})")
            }
        }
        Type::Struct(_) if checked => format!("oidl_{}_decoded", r.name),
        Type::Struct(s) => {
            let path = g.path(3, &s.library, &pascal(&s.name));
            if s.sized {
                format!(
                    "{path}::decode(&{local}.0, {size}, u16::MAX)",
                    size = s.size
                )
            } else {
                format!("<{path} as rt::Fixed>::read(&{local}.0, u16::MAX)")
            }
        }
        Type::Array(elem, count) if record_size(elem).is_some() => finish(format!(
            "<[{}; {count}] as rt::Fixed>::read(&{local}, u16::MAX)",
            g.fixed(3, elem)
        )),
        Type::Array(..) => {
            if checked {
                local
            } else {
                format!("Ok::<_, rt::WireError>({local})")
            }
        }
        Type::Vector(elem, _) if record_size(elem).is_some() => format!("oidl_{}_count", r.name),
        Type::Vector(..) | Type::String(_) => {
            format!("{}.min({name}.len())", result_count(r), name = r.name)
        }
        Type::Bool => finish(format!(
            "rt::decode_bool({local}).ok_or(rt::WireError::Bool)"
        )),
        Type::Enum(e) => {
            let path = g.path(3, &e.library, &enum_name(e));
            finish(format!(
                "{path}::from_raw({local}).ok_or(rt::WireError::Enum)"
            ))
        }
        Type::Bits(b) => {
            let path = g.path(3, &b.library, &pascal(&b.name));
            finish(format!(
                "{path}::from_bits({local}).ok_or(rt::WireError::Bits)"
            ))
        }
        Type::Int(_) => {
            if checked {
                local
            } else {
                format!("Ok::<_, rt::WireError>({local})")
            }
        }
    }
}

fn gen_sys_core_stubs(g: &Gen<'_>, interface: &Interface) -> String {
    let mut t = Text::default();
    let prefix = g.c_prefix();
    t.line(
        "//! The named shim: `origin.core`'s entry points, one `syscall` instruction per number",
    );
    t.line("//! (ADR-0005 B2, ADR-0011 N5). `x86_64` only.");
    t.blank();
    let registers = ["rdi", "rsi", "rdx", "r10", "r8", "r9"];
    for method in &interface.methods {
        let params = abi_params(g, method);
        t.doc(&method.doc);
        t.line("///");
        t.line("/// # Safety");
        t.line("///");
        t.line("/// Each pointer must be valid for the count passed with it, for the duration of the call.");
        t.line("#[unsafe(no_mangle)]");
        let list: Vec<String> = params
            .iter()
            .map(|(n, ty, _)| format!("{n}: {ty}"))
            .collect();
        let result = if method.never { "!" } else { "i64" };
        t.open(format!(
            "pub unsafe extern \"C\" fn {prefix}_{}({}) -> {result} {{",
            method.name,
            list.join(", ")
        ));
        let mut asm_args = Vec::new();
        for (register, (name, _, conversion)) in registers.iter().zip(&params) {
            let value = match *conversion {
                "ptr" => format!("{name}.expose_provenance() as u64"),
                "s" => format!("i64::from({name}) as u64"),
                _ => format!("u64::from({name})"),
            };
            t.line(format!("let oidl_{name}: u64 = {value};"));
            asm_args.push(format!("in(\"{register}\") oidl_{name}"));
        }
        if method.never {
            t.line(
                "// SAFETY: this is the system-call entry of ADR-0005 P4: the number in RAX, the",
            );
            t.line("// arguments in its registers. The call does not return.");
            let mut asm = vec![
                "\"syscall\"".to_string(),
                format!("in(\"rax\") {}_i64", method.ordinal),
            ];
            asm.extend(asm_args);
            asm.push("options(noreturn, nostack)".to_string());
            t.line(format!("unsafe {{ core::arch::asm!({}) }}", asm.join(", ")));
        } else {
            t.line("let oidl_status: i64;");
            t.line(
                "// SAFETY: this is the system-call entry of ADR-0005 P4: the number in RAX, the",
            );
            t.line("// arguments in its registers, RCX and R11 clobbered, every other register");
            t.line("// preserved. The kernel checks each pointer against the caller's own tables.");
            let mut asm = vec![
                "\"syscall\"".to_string(),
                format!("inlateout(\"rax\") {}_i64 => oidl_status", method.ordinal),
            ];
            asm.extend(asm_args);
            asm.push("lateout(\"rcx\") _".to_string());
            asm.push("lateout(\"r11\") _".to_string());
            asm.push("options(nostack)".to_string());
            t.line(format!(
                "unsafe {{ core::arch::asm!({}); }}",
                asm.join(", ")
            ));
            t.line("oidl_status");
        }
        t.shut("}");
        t.blank();
    }
    t.finish()
}

