/// `#` and `.` to bitmaps, one byte per row, the leftmost pixel in the top bit.
const fn compile() -> [[u8; 16]; CELLS] {
    let mut glyphs = [[0u8; 16]; CELLS];
    let mut g = 0;
    while g < CELLS {
        let mut y = 0;
        while y < 16 {
            let line = SHEET[g / PER_ROW * 16 + y].as_bytes();
            assert!(
                line.len() == 8 * PER_ROW + PER_ROW - 1,
                "a sheet row of the wrong width"
            );
            let mut row = 0u8;
            let mut x = 0;
            while x < 8 {
                match line[g % PER_ROW * 9 + x] {
                    b'#' => row |= 0x80 >> x,
                    b'.' => {}
                    _ => panic!("a stray character in the sheet"),
                }
                x += 1;
            }
            glyphs[g][y] = row;
            y += 1;
        }
        g += 1;
    }
    glyphs
}

const TABLE: [[u8; 16]; CELLS] = compile();
/// The compiled glyphs, printable ASCII first.
static GLYPHS: [[u8; 16]; CELLS] = TABLE;
/// The glyph shown for every byte the font has no glyph for: a hollow box.
pub static REPLACEMENT: [u8; 16] = TABLE[CELLS - 1];

/// The bitmap of `byte`, rows from the top, the leftmost pixel in each row's top bit, or
/// [`REPLACEMENT`] for a byte outside `FIRST..=LAST`.
pub fn glyph(byte: u8) -> &'static [u8; 16] {
    if (FIRST..=LAST).contains(&byte) {
        GLYPHS
            .get(usize::from(byte - FIRST))
            .unwrap_or(&REPLACEMENT)
    } else {
        &REPLACEMENT
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_byte_has_a_distinct_drawn_glyph() {
        let printable: Vec<&[u8; 16]> = (FIRST..=LAST).map(glyph).collect();
        for (i, a) in printable.iter().enumerate() {
            let byte = FIRST + i as u8;
            if byte == b' ' {
                assert!(a.iter().all(|&row| row == 0), "the space is blank");
            } else {
                assert!(a.iter().any(|&row| row != 0), "{:?} is blank", byte as char);
            }
            assert_ne!(
                **a, REPLACEMENT,
                "{:?} is the replacement glyph",
                byte as char
            );
            for (j, b) in printable.iter().enumerate().skip(i + 1) {
                assert_ne!(
                    a,
                    b,
                    "{:?} and {:?}",
                    byte as char,
                    (FIRST + j as u8) as char
                );
            }
        }
    }

    #[test]
    fn ink_stays_inside_the_cell_and_off_the_spacing_rows() {
        for byte in FIRST..=LAST {
            let g = glyph(byte);
            assert_eq!(g[0], 0, "{:?}", byte as char);
            assert_eq!(g[1], 0, "{:?}", byte as char);
            assert_eq!(g[15], 0, "{:?}", byte as char);
        }
    }

    #[test]
    fn bytes_without_a_glyph_show_the_replacement() {
        for byte in (0..FIRST).chain(LAST + 1..=255) {
            assert_eq!(*glyph(byte), REPLACEMENT, "{byte:#x}");
        }
        assert!(REPLACEMENT.iter().any(|&row| row != 0));
    }

    /// Confusions a log reader cannot afford: the sheet must keep these apart.
    #[test]
    fn the_look_alikes_differ() {
        for (a, b) in [
            (b'0', b'O'),
            (b'1', b'l'),
            (b'1', b'I'),
            (b'l', b'I'),
            (b'S', b'5'),
        ] {
            let (ga, gb) = (glyph(a), glyph(b));
            let differing_rows = ga.iter().zip(gb).filter(|(x, y)| x != y).count();
            assert!(differing_rows >= 2, "{:?} and {:?}", a as char, b as char);
        }
    }

    #[test]
    fn the_sheet_compiles_the_known_bits_of_a_glyph() {
        // The letter T: a bar across row 3, a stem below it.
        let t = glyph(b'T');
        assert_eq!(t[3], 0b0111_1110);
        assert_eq!(t[4], 0b0001_1000);
        assert_eq!(t[12], 0b0001_1000);
        assert_eq!(t[13], 0);
    }
}
