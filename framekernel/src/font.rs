//! The console font: 8 by 16 bitmaps of ASCII, drawn glyph by glyph for this project
//! (CLAUDE.md §3, §51; ADR-0010).
//!
//! **Provenance.** Every glyph below was drawn by hand on the 8 by 16 grid while this file was
//! written (the drawing was done row by row, in the same `.`/`#` form you see here), by the
//! session that wrote ADR-0010. No existing font's bitmap data, file, image or table was
//! consulted or copied, and none is a dependency; `docs/engineering/SOURCE_PROVENANCE.md`
//! records this. Latin letterforms at this size can only differ so much from one another, so a
//! few glyphs will resemble glyphs in other fonts; none is a copy of one.
//!
//! The design: stems two pixels wide, one-pixel bars, cap height 10 rows (rows 3-12), x-height
//! 7 rows (rows 6-12), descenders to row 14, rows 0, 1 and 15 left clear for line spacing,
//! and columns 0 and 7 usually left clear for letter spacing. The zero is slashed and `1`, `l`
//! and `I` differ, because this font exists to read serial numbers, addresses and logs.
//!
//! The sheet is the source of the data: eight glyphs per row of the sheet, twelve rows,
//! `#` for a set pixel and `.` for a clear one, compiled at build time into [`GLYPHS`]. A sheet
//! with a wrong row length or a stray character does not compile. The last cell is the
//! replacement glyph, shown for every byte the font has no glyph for.

